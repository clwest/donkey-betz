import os
import sys
import django

# Setup Django
sys.path.insert(0, '/Users/donkeyking/development/unified-donkey-betz')
os.environ.setdefault('DJANGO_SETTINGS_MODULE', 'core.settings')
django.setup()

from core.models.agents_registry import UnifiedAgentTemplate, AgentContribution
from content.models import ImageHistory

def verify_agent_registration():
    """Verify the trained-creation-agent is registered."""
    print("=" * 80)
    print("🔍 Verifying Agent Registration - Session 135")
    print("=" * 80)
    print()

    # Check if agent exists
    agent = UnifiedAgentTemplate.objects.filter(name='trained-creation-agent').first()

    if not agent:
        print("❌ trained-creation-agent NOT FOUND in database!")
        print("   Run register_trained_creation_agent.py first")
        return None

    print("✅ Agent found in database:")
    print(f"   Name: {agent.name}")
    print(f"   Display Name: {agent.display_name}")
    print(f"   Specialization: {agent.specialization}")
    print(f"   Active: {agent.is_active}")
    print(f"   Capabilities: {', '.join(agent.capabilities[:3])}...")
    print()

    return agent


def check_existing_images(agent):
    """Check for images that were generated by trained-creation-agent."""
    print("📊 Checking for images with agent_name='trained-creation-agent'...")
    print()

    # Find images with this agent_name in parameters
    images = ImageHistory.objects.filter(
        model_used__icontains='replicate',
        style='lora-trained'
    ).order_by('-created_at')[:10]

    if not images:
        print("   No LoRA-trained images found")
        return

    print(f"   Found {images.count()} recent LoRA-trained images")
    print()

    for img in images:
        print(f"   Image #{img.get_sequential_number()}:")
        print(f"      ID: {img.id}")
        print(f"      Model: {img.model_used}")
        print(f"      Style: {img.style}")
        print(f"      Project: {img.project.name if img.project else 'None'}")
        print(f"      Agent field: {img.agent.name if img.agent else 'None'}")

        # Check if contribution exists
        contribution = AgentContribution.objects.filter(
            agent=agent,
            image=img
        ).first()

        if contribution:
            print(f"      ✅ Contribution tracked: {contribution.contribution_type}")
        else:
            print(f"      ⚠️  No contribution record (expected if created before Session 135)")

        print()


def test_contribution_tracking(agent):
    """Simulate what happens when a new image is saved with agent_name."""
    print("🧪 Testing Contribution Tracking Logic...")
    print()

    # This tests the logic in save_to_history() from core/views_image.py
    agent_lookup = UnifiedAgentTemplate.objects.filter(
        name='trained-creation-agent',
        is_active=True
    ).first()

    if agent_lookup:
        print("   ✅ Agent lookup by name works!")
        print(f"      Found: {agent_lookup.display_name}")
        print()
        print("📝 When TrainedCreationAgent generates images:")
        print("   1. save_to_history() receives agent_name='trained-creation-agent'")
        print("   2. Looks up UnifiedAgentTemplate by name")
        print("   3. Creates AgentContribution record")
        print("   4. Links contribution to project and image")
        print()
        print("✅ Agent contribution tracking is NOW ENABLED!")
    else:
        print("   ❌ Agent lookup failed - something is wrong")


def check_agent_contributions_count(agent):
    """Check how many contributions this agent has."""
    print("📈 Agent Contribution Stats:")
    print()

    total_contributions = AgentContribution.objects.filter(agent=agent).count()
    image_contributions = AgentContribution.objects.filter(
        agent=agent,
        image__isnull=False
    ).count()

    print(f"   Total contributions: {total_contributions}")
    print(f"   Image contributions: {image_contributions}")

    if total_contributions > 0:
        print()
        print("   Recent contributions:")
        recent = AgentContribution.objects.filter(agent=agent).order_by('-created_at')[:5]
        for contrib in recent:
            print(f"      - {contrib.contribution_type}: {contrib.project.name if contrib.project else 'No project'}")


if __name__ == "__main__":
    agent = verify_agent_registration()

    if agent:
        check_existing_images(agent)
        test_contribution_tracking(agent)
        check_agent_contributions_count(agent)

        print()
        print("=" * 80)
        print("✅ Verification Complete!")
        print()
        print("Next steps:")
