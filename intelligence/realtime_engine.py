    def _detect_arbitrage(self, game: Dict) -> List[MarketOpportunity]:
        """Detect arbitrage opportunities"""
        opportunities = []

        try:
            bookmakers = game.get('bookmakers', [])
            if len(bookmakers) < 2:
                return opportunities

            # Simple arbitrage detection for h2h markets
            best_home_odds = None
            best_away_odds = None
            best_home_book = None
            best_away_book = None

            for bookmaker in bookmakers:
                for market in bookmaker.get('markets', []):
                    if market['key'] == 'h2h':
                        for outcome in market['outcomes']:
                            price = outcome['price']
                            if 'home' in outcome['name'].lower() or outcome['name'] == game.get('home_team'):
                                if not best_home_odds or price > best_home_odds:
                                    best_home_odds = price
                                    best_home_book = bookmaker['title']
                            else:
                                if not best_away_odds or price > best_away_odds:
                                    best_away_odds = price
                                    best_away_book = bookmaker['title']

            if best_home_odds and best_away_odds:
                # Calculate arbitrage
                implied_prob = (1/((best_home_odds+100)/100 if best_home_odds > 0 else 100/abs(best_home_odds))) + \
                              (1/((best_away_odds+100)/100 if best_away_odds > 0 else 100/abs(best_away_odds)))

                if implied_prob < 0.95:  # Arbitrage opportunity
                    edge = (1 - implied_prob) * 100

                    opp = MarketOpportunity(
                        id=f"arb_{game.get('id', 'unknown')}_{int(datetime.now().timestamp())}",
                        type='arbitrage',
                        domain='SPORTS_BETTING',
                        entity=f"{game.get('away_team', 'Away')} vs {game.get('home_team', 'Home')}",
                        description=f"Arbitrage opportunity: {best_away_book} ({best_away_odds}) vs {best_home_book} ({best_home_odds})",
                        edge=edge,
                        confidence=0.95,
                        profit_potential=edge * 10,  # Assume $1000 bet
                        risk_level=0.1,  # Low risk for arbitrage
                        time_window=60,  # 1 hour window
                        required_capital=1000,
                        liquidity_score=0.8,
                        historical_win_rate=0.98,  # Arbitrage is near-guaranteed
                        market_data={
                            'best_home_odds': best_home_odds,
                            'best_away_odds': best_away_odds,
                            'implied_probability': implied_prob
                        },
                        triggers=[f"Odds discrepancy between {best_home_book} and {best_away_book}"],
                        exchanges=[best_home_book, best_away_book],
                        timestamp=datetime.now().isoformat(),
                        status='active',
                        alert_level='critical' if edge > 5 else 'high'
                    )
                    opportunities.append(opp)

        except Exception as e:
            logger.error(f"Arbitrage detection error: {e}")

        return opportunities

    def _detect_value_bets(self, game: Dict) -> List[MarketOpportunity]:
        """Detect value betting opportunities using basic analysis"""
        opportunities = []

        try:
            # Simple value detection - look for odds that seem off
            bookmakers = game.get('bookmakers', [])
            if not bookmakers:
                return opportunities

            # Calculate average odds for comparison
            home_odds_list = []
            away_odds_list = []

            for bookmaker in bookmakers:
                for market in bookmaker.get('markets', []):
                    if market['key'] == 'h2h':
                        for outcome in market['outcomes']:
                            price = outcome['price']
                            if 'home' in outcome['name'].lower() or outcome['name'] == game.get('home_team'):
                                home_odds_list.append(price)
                            else:
                                away_odds_list.append(price)

            if len(home_odds_list) >= 2 and len(away_odds_list) >= 2:
                avg_home = np.mean(home_odds_list)
                avg_away = np.mean(away_odds_list)

                # Look for outliers (basic value detection)
                for bookmaker in bookmakers:
                    for market in bookmaker.get('markets', []):
                        if market['key'] == 'h2h':
                            for outcome in market['outcomes']:
                                price = outcome['price']
                                is_home = 'home' in outcome['name'].lower() or outcome['name'] == game.get('home_team')
                                avg_price = avg_home if is_home else avg_away

                                # If price is significantly better than average
                                if price > avg_price * 1.1:  # 10% better odds
                                    edge = ((price - avg_price) / avg_price) * 100

                                    opp = MarketOpportunity(
                                        id=f"value_{game.get('id', 'unknown')}_{outcome['name']}_{int(datetime.now().timestamp())}",
                                        type='value_bet',
                                        domain='SPORTS_BETTING',
                                        entity=f"{game.get('away_team', 'Away')} vs {game.get('home_team', 'Home')}",
                                        description=f"Value bet on {outcome['name']} at {bookmaker['title']} ({price} vs avg {avg_price:.0f})",
                                        edge=edge,
                                        confidence=0.7,
                                        profit_potential=edge * 5,
                                        risk_level=0.4,
                                        time_window=120,
                                        required_capital=500,
                                        liquidity_score=0.7,
                                        historical_win_rate=0.65,
                                        market_data={
                                            'current_odds': price,
                                            'average_odds': avg_price,
                                            'team': outcome['name']
                                        },
                                        triggers=[f"Odds {price} significantly above market average {avg_price:.0f}"],
                                        exchanges=[bookmaker['title']],
                                        timestamp=datetime.now().isoformat(),
                                        status='active',
                                        alert_level='medium' if edge > 8 else 'low'
                                    )
                                    opportunities.append(opp)

        except Exception as e:
            logger.error(f"Value bet detection error: {e}")

        return opportunities

