    def get_current_opportunities(self) -> List[Dict]:
        """Get current active opportunities"""
        active_opportunities = []
        cutoff_time = datetime.now() - timedelta(hours=1)

        for opp in self.opportunities.values():
            opp_time = datetime.fromisoformat(opp.timestamp)
            if opp_time > cutoff_time and opp.status == 'active':
                active_opportunities.append(asdict(opp))

        return active_opportunities

    def get_current_predictions(self) -> List[Dict]:
        """Get current active predictions"""
        active_predictions = []
        now = datetime.now()

        for pred in self.predictions.values():
            expires_at = datetime.fromisoformat(pred.expires_at)
            if expires_at > now:
                active_predictions.append(asdict(pred))

        return active_predictions


