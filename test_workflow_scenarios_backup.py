    def generate_scenario_report(self):
        """Generate detailed scenario test report"""
        total_scenarios = self.scenarios_passed + self.scenarios_failed
        success_rate = (self.scenarios_passed / total_scenarios * 100) if total_scenarios > 0 else 0
        
        print("\n" + "="*60)
        print("📊 WORKFLOW SCENARIO TEST RESULTS")
        print("="*60)
        print(f"Total Scenarios: {total_scenarios}")
        print(f"Passed: {self.scenarios_passed} ✅")
        print(f"Failed: {self.scenarios_failed} ❌") 
        print(f"Success Rate: {success_rate:.1f}%")
        print("\nDetailed Results:")
        
        for i, result in enumerate(self.detailed_results, 1):
            print(f"\n{i}. {result['scenario'].replace('_', ' ').title()}")
            print(f"   Status: {result['status']}")
            if result['status'] == 'PASSED':
                for key, value in result.items():
                    if key not in ['scenario', 'status']:
                        print(f"   {key}: {value}")
            else:
                print(f"   Error: {result.get('error', 'Unknown')}")
        
        return {
            "total_scenarios": total_scenarios,
            "passed": self.scenarios_passed,
            "failed": self.scenarios_failed, 
            "success_rate": success_rate,
            "detailed_results": self.detailed_results
        }


