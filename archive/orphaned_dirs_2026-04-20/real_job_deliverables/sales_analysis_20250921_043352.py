import pandas as pd
import matplotlib.pyplot as plt

def read_sales_data(file_path):
    """
    Reads sales data from a CSV file.

    Parameters:
    file_path (str): The path to the CSV file.

    Returns:
    DataFrame: A pandas DataFrame containing the sales data.
    """
    try:
        data = pd.read_csv(file_path)
        return data
    except FileNotFoundError:
        print(f"Error: The file {file_path} was not found.")
        return None
    except pd.errors.EmptyDataError:
        print("Error: The file is empty.")
        return None
    except pd.errors.ParserError:
        print("Error: There was a problem parsing the file.")
        return None

def calculate_total_sales(data):
    """
    Calculates total sales by product and region.

    Parameters:
    data (DataFrame): The sales data.

    Returns:
    DataFrame: A DataFrame with total sales aggregated by product and region.
    """
    total_sales = data.groupby(['product', 'region'], as_index=False)['sales_amount'].sum()
    return total_sales

def visualize_sales(total_sales):
    """
    Generates a bar chart for total sales by product and region.

    Parameters:
    total_sales (DataFrame): The aggregated sales data.
    """
    # Pivot the data for better visualization
    pivot_data = total_sales.pivot(index='product', columns='region', values='sales_amount').fillna(0)

    # Create a bar chart
    pivot_data.plot(kind='bar', figsize=(10, 6))
    plt.title('Total Sales by Product and Region')
    plt.xlabel('Product')
    plt.ylabel('Total Sales Amount')
    plt.xticks(rotation=45)
    plt.legend(title='Region')
    plt.tight_layout()
    plt.show()

def export_results(total_sales, output_file):
    """
    Exports the total sales data to a new CSV file.

    Parameters:
    total_sales (DataFrame): The aggregated sales data.
    output_file (str): The path to the output CSV file.
    """
    try:
        total_sales.to_csv(output_file, index=False)
        print(f"Results exported to {output_file}")
    except Exception as e:
        print(f"Error exporting results: {e}")

def main(input_file, output_file):
    """
    Main function to execute the sales data analysis.

    Parameters:
    input_file (str): The path to the input CSV file.
    output_file (str): The path to the output CSV file.
    """
    # Step 1: Read the sales data
    sales_data = read_sales_data(input_file)
    if sales_data is None:
        return

    # Step 2: Calculate total sales
    total_sales = calculate_total_sales(sales_data)

    # Step 3: Visualize the sales data
    visualize_sales(total_sales)

    # Step 4: Export the results to a new CSV file
    export_results(total_sales, output_file)

if __name__ == "__main__":
    # Specify the input and output file paths
    input_csv_file = 'sales_data.csv'  # Change this to your input file path
