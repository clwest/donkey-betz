import pandas as pd
import matplotlib.pyplot as plt

def read_csv(file_path):
    """
    This function reads a CSV file and returns a DataFrame.
    """
    try:
        df = pd.read_csv(file_path)
        return df
    except FileNotFoundError:
        print(f"File not found: {file_path}")
        return None
    except Exception as e:
        print(f"Error occurred: {e}")
        return None

def calculate_total_sales(df):
    """
    This function calculates total sales by product and region.
    """
    try:
        total_sales = df.groupby(['product', 'region'])['sales_amount'].sum().reset_index()
        return total_sales
    except Exception as e:
        print(f"Error occurred: {e}")
        return None

def generate_visualization(df):
    """
    This function generates a bar chart for total sales by product and region.
    """
    try:
        df.plot(kind='bar', x='product', y='sales_amount', color='blue')
        plt.title('Total Sales by Product and Region')
        plt.xlabel('Product')
        plt.ylabel('Total Sales')
        plt.show()
    except Exception as e:
        print(f"Error occurred: {e}")

def export_to_csv(df, file_path):
    """
    This function exports DataFrame to a new CSV file.
    """
    try:
        df.to_csv(file_path, index=False)
        print(f"Data exported to {file_path}")
    except Exception as e:
        print(f"Error occurred: {e}")

def main():
    """
    Main function to run the script.
    """
    # Read CSV
    df = read_csv('sales_data.csv')

    if df is not None:
        # Calculate total sales
        total_sales = calculate_total_sales(df)

        if total_sales is not None:
            # Generate visualization
            generate_visualization(total_sales)

            # Export to new CSV
            export_to_csv(total_sales, 'total_sales.csv')

if __name__ == "__main__":
    main()