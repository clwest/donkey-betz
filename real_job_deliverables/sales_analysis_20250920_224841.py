import pandas as pd
import matplotlib.pyplot as plt
import os

def read_sales_data(file_path):
    """
    Reads sales data from a CSV file.

    Parameters:
    file_path (str): The path to the CSV file.

    Returns:
    DataFrame: A pandas DataFrame containing the sales data.
    """
    try:
        data = pd.read_csv(file_path)
        return data
    except FileNotFoundError:
        print(f"Error: The file {file_path} was not found.")
        return None
    except pd.errors.EmptyDataError:
        print("Error: The file is empty.")
        return None
    except pd.errors.ParserError:
        print("Error: There was a problem parsing the file.")
        return None

def calculate_total_sales(data):
    """
    Calculates total sales by product and region.

    Parameters:
    data (DataFrame): A pandas DataFrame containing the sales data.

    Returns:
    DataFrame: A DataFrame with total sales by product and region.
    """
    total_sales = data.groupby(['product', 'region'], as_index=False)['sales_amount'].sum()
    return total_sales

def visualize_sales(total_sales):
    """
    Generates a bar chart for total sales by product and region.

    Parameters:
    total_sales (DataFrame): A DataFrame with total sales by product and region.
    """
    pivot_table = total_sales.pivot(index='product', columns='region', values='sales_amount').fillna(0)
    pivot_table.plot(kind='bar', figsize=(10, 6))
    plt.title('Total Sales by Product and Region')
    plt.ylabel('Sales Amount')
    plt.xlabel('Product')
    plt.xticks(rotation=45)
    plt.legend(title='Region')
    plt.tight_layout()
    plt.show()

def export_results(total_sales, output_file_path):
    """
    Exports the total sales DataFrame to a new CSV file.

    Parameters:
    total_sales (DataFrame): A DataFrame with total sales by product and region.
    output_file_path (str): The path where the output CSV file will be saved.
    """
    try:
        total_sales.to_csv(output_file_path, index=False)
        print(f"Results exported successfully to {output_file_path}.")
    except Exception as e:
        print(f"Error exporting results: {e}")

def main():
    input_file_path = 'sales_data.csv'  # Change this to your input file path
    output_file_path = 'total_sales_by_product_region.csv'  # Output file path

    # Read sales data
    sales_data = read_sales_data(input_file_path)
    if sales_data is None:
        return  # Exit if data could not be read

    # Calculate total sales
    total_sales = calculate_total_sales(sales_data)

    # Visualize total sales
    visualize_sales(total_sales)

    # Export results to CSV
    export_results(total_sales, output_file_path)

if __name__ == "__main__":
    main()