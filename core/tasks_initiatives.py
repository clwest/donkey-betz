def _impl_cleanup_junk_initiatives(stale_days: int = 7):
    """
    Session 926/943: Clean up junk initiatives to prevent pipeline backlogs.

    Session 943 UPDATE: Now attempts to FIX names using title generator before deleting.
    Only deletes if name cannot be fixed (no usable content to extract from).

    FIXES initiatives with junk name patterns by regenerating clean titles.
    DELETES initiatives that have no salvageable content.
    ARCHIVES initiatives that are stale (might be legitimate, just slow).

    Args:
        stale_days: Archive initiatives with no Stage 1 doc after this many days

    Returns:
        Dict with cleanup statistics
    """
    from django.utils import timezone
    from datetime import timedelta
    from django.db.models import Q
    from core.models_document_registry import Initiative, InitiativeStage
    from core.services.initiative_title_generator import generate_initiative_title, _is_valid_title

    logger.info(f"🧹 [INITIATIVE-CLEANUP] Starting cleanup...")

    try:
        now = timezone.now()
        cutoff = now - timedelta(days=stale_days)

        stats = {
            'names_fixed': 0,
            'junk_deleted': 0,
            'stale_archived': 0,
            'stage_invariant_fixed': 0,
        }

        # 1. FIX or DELETE junk name patterns
        # Session 943: Try to fix names before deleting
        # Session 945: Added Auto-created and other common junk patterns
        junk_patterns = Q(name__icontains='[Learned]') | \
                       Q(name__icontains='[Synthesis]') | \
                       Q(name__startswith='driven ') | \
                       Q(name__startswith='plan ') | \
                       Q(name__startswith='of-') | \
                       Q(name__startswith='analysis ') | \
                       Q(name__startswith="Feature name:") | \
                       Q(name__startswith="Auto-created From") | \
                       Q(name__startswith="A '") | \
                       Q(name__startswith="An '") | \
                       Q(name__regex=r'^[a-z]')  # Starts with lowercase (fragment)

        junk_initiatives = Initiative.objects.filter(
            status='ACTIVE'
        ).filter(junk_patterns)

        for init in junk_initiatives:
            old_name = init.name[:60]

            # Session 943: Try to generate a clean title from available content
            # Use description, parent_topic, or original name as sources
            content_sources = [
                init.description or '',
                init.parent_topic or '',
                init.name or '',
            ]
            combined_content = ' '.join(content_sources)

            # Try to generate a valid title
            new_title = generate_initiative_title(
                content=combined_content,
                topic_hint=init.parent_topic,
                max_length=60,
                use_llm=False  # Use heuristics only for speed
            )

            # Session 945: Check if new title is still junk (Auto-created, etc.)
            new_title_is_junk = (
                new_title and (
                    new_title.startswith("Auto-created") or
                    new_title.startswith("A '") or
                    new_title.startswith("An '") or
                    new_title[0].islower()  # Starts lowercase
                )
            )

            # Check if the new title is valid, different, and NOT still junk
            if new_title and _is_valid_title(new_title) and new_title != init.name and not new_title_is_junk:
                # Session 943: Check for duplicate name before saving
                if Initiative.objects.filter(name=new_title).exclude(id=init.id).exists():
                    # Add unique suffix to avoid duplicate
                    import uuid
                    suffix = str(uuid.uuid4())[:6]
                    new_title = f"{new_title[:53]} ({suffix})"

                try:
                    init.name = new_title
                    init.save(skip_invariant_check=True)  # Skip stage check for name-only fix
                    stats['names_fixed'] += 1
                    logger.info(f"✨ [INITIATIVE-CLEANUP] Fixed name: '{old_name}' → '{new_title}'")
                except Exception as save_err:
                    logger.warning(f"⚠️ Could not fix name '{old_name}': {save_err}")
                    continue  # Skip deletion, leave as-is
            else:
                # Cannot fix or new title still junk - delete it
                init.delete()
                stats['junk_deleted'] += 1
                logger.info(f"🗑️ [INITIATIVE-CLEANUP] Deleted unfixable: {old_name}")

        # 2. Session 943: Fix stage invariant violations
        # Find initiatives where current_stage > max_approved + 1
        for init in Initiative.objects.filter(status='ACTIVE'):
            max_approved = init.get_max_approved_stage()
            max_allowed = max_approved + 1
            if init.current_stage > max_allowed:
                old_stage = init.current_stage
                init.current_stage = max_allowed
                init.save(skip_invariant_check=True)
                stats['stage_invariant_fixed'] += 1
                logger.info(
                    f"🔧 [INITIATIVE-CLEANUP] Fixed stage: {init.name[:40]}... "
                    f"(was {old_stage}, now {max_allowed})"
                )

        # 3. ARCHIVE stale initiatives (no Stage 1 doc after X days)
        # These might be legitimate, just slow - archive instead of delete
        # Session 945: Skip if founder_intent_set or has recent conversation activity
        from core.models_unified_system import HiveMindSession

        stale_initiatives = Initiative.objects.filter(
            status='ACTIVE',
            created_at__lt=cutoff
        ).exclude(
            id__in=InitiativeStage.objects.filter(
                stage=1,
                document__isnull=False
            ).values_list('initiative_id', flat=True)
        )

        stats['skipped_with_activity'] = 0

        for init in stale_initiatives:
            # Session 945: Don't archive if founder has explicitly set intent
            if init.founder_intent_set:
                stats['skipped_with_activity'] += 1
                logger.debug(f"⏭️ [INITIATIVE-CLEANUP] Skipped (founder intent): {init.name[:40]}")
                continue

            # Session 945: Don't archive if there's recent activity
            recent_activity_cutoff = now - timedelta(days=3)

            # Check last_activity_at field first (most accurate)
            if init.last_activity_at and init.last_activity_at >= recent_activity_cutoff:
                stats['skipped_with_activity'] += 1
                logger.debug(f"⏭️ [INITIATIVE-CLEANUP] Skipped (recent activity): {init.name[:40]}")
                continue

            # Fallback: check for recent conversations
            has_recent_convo = HiveMindSession.objects.filter(
                initiative_id=init.id,
                created_at__gte=recent_activity_cutoff
            ).exists()

            if has_recent_convo:
                stats['skipped_with_activity'] += 1
                logger.debug(f"⏭️ [INITIATIVE-CLEANUP] Skipped (recent convo): {init.name[:40]}")
                continue

            init.status = 'ARCHIVED'
            init.save(skip_invariant_check=True)
            stats['stale_archived'] += 1
            logger.info(f"📦 [INITIATIVE-CLEANUP] Archived stale: {init.name[:50]}")

        logger.info(
            f"🧹 [INITIATIVE-CLEANUP] Complete - "
            f"fixed {stats['names_fixed']} names, "
            f"deleted {stats['junk_deleted']} junk, "
            f"archived {stats['stale_archived']} stale, "
            f"skipped {stats.get('skipped_with_activity', 0)} with activity, "
            f"fixed {stats['stage_invariant_fixed']} stage violations"
        )

        return stats

    except Exception as e:
        logger.error(f"🧹 [INITIATIVE-CLEANUP] Failed: {e}", exc_info=True)
        raise




def _impl_execute_initiative_stage_task(
self,
    initiative_id: str,
    stage_num: int,
    agent_name: str,
    task: str,
    context: Dict[str, Any] = None
):
    """
    Session 884: Execute a task linked to an Initiative stage.
    Session 1017: Added soft_time_limit=2700 (45 min) to kill hung agents.
    Session 1058: Raised to 3600/3900 (60/65 min). NOTE: soft_time_limit does NOT
    enforce on --pool=threads (Railway) — SIGUSR1 only works with prefork. The
    WorkflowAgent wall-clock guard is the real timeout protection.

    This task is part of the Conversation-to-Initiative pipeline.
    When complete, it updates the stage and potentially advances the Initiative.

    Args:
        initiative_id: ID of the Initiative
        stage_num: Stage number (1-5)
        agent_name: Name of the agent to execute the task
        task: Task description
        context: Additional context

    Returns:
        Dict with execution result and stage update info
    """
    from core.agent_router import AgentRouter
    from core.services.conversation_initiative_pipeline import handle_stage_task_completion

    context = context or {}
    execution_start = time.time()

    # Fix: Strip accumulated [Conversation] [Conversation] prefixes from task text
    # These accumulate when topics cycle through ScheduledConversation → HiveMind → initiative pipeline
    from core.services.conversation_initiative_pipeline import strip_bracket_prefixes
    task = strip_bracket_prefixes(task)

    logger.info(
        f"[execute_initiative_stage_task] Starting: {agent_name} for Initiative {initiative_id[:8]} "
        f"Stage {stage_num}: '{task[:50]}...'"
    )

    try:
        # Execute the agent task with wall-clock timeout guard
        # Session 1075: Same pattern as execute_agent_task — prevents 35min watchdog hangs
        router = AgentRouter()
        from concurrent.futures import ThreadPoolExecutor as _TPE2, TimeoutError as _FuturesTimeout2

        _STAGE_TIMEOUTS = {
            'CompetitorAnalysisAgent': 600,
            'ContentWriterAgent': 600,
            'ContentDistributionAgent': 300,
            'ResearchAgent': 900,
            'CustomerResearchAgent': 900,
            'TrendAnalysisAgent': 600,
        }
        _stage_timeout = _STAGE_TIMEOUTS.get(agent_name, 1200)

        def _run_stage_route():
            from django.db import close_old_connections
            close_old_connections()
            try:
                return router.route(
                    agent_name=agent_name,
                    task=task,
                    context={
                        'source': 'initiative_stage_task',
                        'initiative_id': initiative_id,
                        'stage_num': stage_num,
                        **context
                    }
                )
            finally:
                close_old_connections()

        try:
            _pool2 = _TPE2(max_workers=1)
            _future2 = _pool2.submit(_run_stage_route)
            try:
                result = _future2.result(timeout=_stage_timeout)
            finally:
                _pool2.shutdown(wait=False)
        except _FuturesTimeout2:
            _elapsed = time.time() - execution_start
            logger.error(
                f"[execute_initiative_stage_task] WALL-CLOCK TIMEOUT: {agent_name} exceeded "
                f"{_stage_timeout}s limit for Initiative {initiative_id[:8]} Stage {stage_num}"
            )
            _record_timeout_signature(
                agent_name=agent_name,
                timeout_source='initiative_wall_clock',
                elapsed_seconds=_elapsed,
                task_name='core.tasks.execute_initiative_stage_task',
            )
            from core.agents.base_agent import AgentResult
            result = AgentResult(
                success=False,
                error=f'{agent_name} exceeded {_stage_timeout}s wall-clock timeout (initiative stage task)',
                agent_name=agent_name,
                execution_time_ms=int(_elapsed * 1000),
            )

        execution_time_ms = int((time.time() - execution_start) * 1000)

        # Session 1041: Use helper to extract real content from AgentResult.
        # Many agents put summaries in .message and actual content in .data.
        actual_content = _extract_agent_content(result)

        # Build task result for stage handler
        task_result = {
            'success': result.success,
            'content': actual_content[:5000] if actual_content else '',
            'error': result.error,
            'execution_time_ms': execution_time_ms,
        }

        # Handle stage completion (update stage, advance if ready, enrich deliverable)
        stage_update = handle_stage_task_completion(
            initiative_id=initiative_id,
            stage_num=stage_num,
            agent_name=agent_name,
            task_result=task_result,
        )

        if execution_time_ms > 2_400_000:  # 40 min
            logger.warning(
                f"[execute_initiative_stage_task] SLOW AGENT: {agent_name} took "
                f"{execution_time_ms // 60_000}min — approaching timeout"
            )

        logger.info(
            f"[execute_initiative_stage_task] Completed: {agent_name} Stage {stage_num} "
            f"(success={result.success}, stage_advanced={stage_update.get('stage_advanced')})"
        )

        # Session 908: Create WorkspaceOperation for Initiative tracking
        if result.success and result.content:
            try:
                from core.models_document_registry import Initiative
                from core.models_skin_layer import WorkspaceOperation
                from core.services.workspace_manager import WorkspaceManager
                from django.contrib.auth import get_user_model
                User = get_user_model()

                initiative = Initiative.objects.get(id=initiative_id)

                # Get workspace - prefer initiative's target, fall back to user's active
                workspace = initiative.target_workspace
                if not workspace:
                    # Try to get system user's workspace
                    system_user = User.objects.filter(username='system_autonomous').first()
                    if system_user:
                        manager = WorkspaceManager(system_user)
                        workspace = manager.get_active_workspace()

                if workspace:
                    # Create workspace operation to track this Initiative work
                    WorkspaceOperation.objects.create(
                        workspace=workspace,
                        user=workspace.user,
                        agent_name=agent_name,
                        agent_task=task[:500] if task else '',
                        operation_type='file_create',
                        file_path=f'initiatives/{initiative.name[:50]}/stage_{stage_num}.md',
                        file_content_after=result.content[:10000] if result.content else '',
                        success=True,
                        initiative_id=initiative.id,
                        trigger_source='initiative',
                        run_mode='production',
                        execution_time_ms=execution_time_ms,
                    )
                    logger.info(f"[execute_initiative_stage_task] Created WorkspaceOperation for {initiative.name[:30]} Stage {stage_num}")
            except Exception as ws_error:
                logger.warning(f"[execute_initiative_stage_task] Could not create WorkspaceOperation: {ws_error}")

        return {
            'success': result.success,
            'agent_name': agent_name,
            'initiative_id': initiative_id,
            'stage_num': stage_num,
            'task': task,
            'content': result.content[:1000] if result.content else None,
            'execution_time_ms': execution_time_ms,
            'stage_update': stage_update,
        }

    except SoftTimeLimitExceeded:
        execution_time_ms = int((time.time() - execution_start) * 1000)
        logger.error(f"[execute_initiative_stage_task] KILLED by soft_time_limit: {agent_name} after {execution_time_ms}ms")
        try:
            handle_stage_task_completion(
                initiative_id=initiative_id,
                stage_num=stage_num,
                agent_name=agent_name,
                task_result={'success': False, 'error': 'Celery soft_time_limit exceeded (60 min)'},
            )
        except Exception as _e:
            logger.warning(
                "tasks_initiatives._impl_execute_initiative_stage_task: swallowed (%s: %s) — degraded",
                type(_e).__name__, _e,
            )
        return {
            'success': False,
            'agent_name': agent_name,
            'initiative_id': initiative_id,
            'stage_num': stage_num,
            'task': task,
            'error': 'Celery soft_time_limit exceeded (60 min)',
            'execution_time_ms': execution_time_ms,
        }

    except Exception as e:
        execution_time_ms = int((time.time() - execution_start) * 1000)
        logger.error(f"[execute_initiative_stage_task] Failed: {agent_name} - {e}")

        # Still try to update stage with failure info
        try:
            handle_stage_task_completion(
                initiative_id=initiative_id,
                stage_num=stage_num,
                agent_name=agent_name,
                task_result={'success': False, 'error': str(e)},
            )
        except Exception as e2:
            logger.warning(f"Failed to record stage task failure: {e2}")

        if self.request.retries < self.max_retries:
            raise self.retry(exc=e)

        return {
            'success': False,
            'agent_name': agent_name,
            'initiative_id': initiative_id,
            'stage_num': stage_num,
            'task': task,
            'error': str(e),
            'execution_time_ms': execution_time_ms,
        }


