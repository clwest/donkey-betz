def _impl_process_distribution(self, distribution_id: str):
    """
    Process a content distribution to a platform.

    This task handles the actual upload/submission process for each platform,
    updating the distribution status as it progresses.
    """
    logger.info(f"🚀 [DISTRIBUTION] Processing distribution {distribution_id}")

    try:
        from core.models_unified_system import ContentDistribution
        from django.utils import timezone

        distribution = ContentDistribution.objects.select_related(
            'platform_account__platform',
            'image_history',
            'video_history',
            'user'
        ).get(id=distribution_id)

        # Check if already processed or cancelled
        if distribution.status in ['live', 'removed', 'rejected']:
            logger.info(f"🚀 [DISTRIBUTION] {distribution_id} already processed: {distribution.status}")
            return {'status': 'skipped', 'reason': f'Already {distribution.status}'}

        # Update to processing status
        distribution.status = 'processing'
        distribution.save()

        platform_name = distribution.platform_account.platform.name.lower()

        # Platform-specific processing
        result = None

        if 'etsy' in platform_name:
            result = process_etsy_distribution(distribution)
        elif 'gumroad' in platform_name:
            result = process_gumroad_distribution(distribution)
        elif 'shutterstock' in platform_name:
            result = process_shutterstock_distribution(distribution)
        else:
            # Generic processing - just mark as pending review
            result = {
                'success': True,
                'status': 'pending',
                'message': f'Queued for {platform_name} - manual upload required'
            }

        if result.get('success'):
            distribution.status = result.get('status', 'live')
            distribution.platform_listing_id = result.get('listing_id', '')
            distribution.platform_listing_url = result.get('url', '')
            if distribution.status == 'live':
                distribution.listed_at = timezone.now()

            # Update platform metadata with result
            metadata = distribution.platform_metadata or {}
            metadata['process_result'] = result
            metadata['processed_at'] = timezone.now().isoformat()
            distribution.platform_metadata = metadata
            distribution.save()

            # Update account stats
            account = distribution.platform_account
            account.total_items_listed += 1
            account.save()

            logger.info(f"🚀 [DISTRIBUTION] Successfully processed {distribution_id} to {platform_name}")
            return {
                'status': 'success',
                'distribution_id': distribution_id,
                'platform': platform_name,
                'listing_status': distribution.status
            }
        else:
            # Failed
            distribution.status = 'rejected'
            distribution.rejection_reason = result.get('error', 'Unknown error')
            distribution.save()

            logger.error(f"🚀 [DISTRIBUTION] Failed to process {distribution_id}: {result.get('error')}")
            return {
                'status': 'failed',
                'distribution_id': distribution_id,
                'error': result.get('error')
            }

    except ContentDistribution.DoesNotExist:
        logger.error(f"🚀 [DISTRIBUTION] Distribution {distribution_id} not found")
        return {'status': 'failed', 'error': 'Distribution not found'}

    except Exception as e:
        logger.exception(f"🚀 [DISTRIBUTION] Error processing {distribution_id}: {e}")
        # Retry on transient errors
        raise self.retry(exc=e, countdown=60 * (self.request.retries + 1))




def _impl_generate_video_content_pack_task(self, video_id, user_id, language='en'):
    """
    Generate a content pack for a video using its transcript.

    Produces: titles (3+), summary, key points, chapters (timestamped),
    YouTube description + tags. Saved as a Deliverable.
    """
    from content.models import VideoTranscript, VideoHistory
    from core.models_deliverables import Deliverable
    from django.contrib.auth import get_user_model
    from openai import OpenAI
    from django.conf import settings as django_settings

    User = get_user_model()

    try:
        user = User.objects.get(id=user_id)
        video = VideoHistory.objects.get(id=video_id, user=user)

        # Find latest completed transcript
        transcript = VideoTranscript.objects.filter(
            video=video, status='completed'
        ).order_by('-created_at').first()

        if not transcript or not transcript.text:
            raise ValueError(f"No completed transcript found for video {video_id}")

        video_title = (video.prompt or video.original_filename or 'Untitled Video')[:200]
        duration_str = ''
        if transcript.duration_seconds:
            mins = int(transcript.duration_seconds // 60)
            secs = int(transcript.duration_seconds % 60)
            duration_str = f" ({mins}:{secs:02d})"

        # Build chapters hint from segments
        segments = transcript.segments_json or []
        segment_hint = ''
        if segments:
            # Sample ~10 evenly spaced segments for chapter hints
            step = max(1, len(segments) // 10)
            sampled = segments[::step][:10]
            segment_hint = '\n'.join(
                f"[{int(s['start']//60)}:{int(s['start']%60):02d}] {s['text']}"
                for s in sampled
            )

        prompt = f"""Analyze this video transcript and generate a content pack.

Video: {video_title}{duration_str}
Language: {language}

Transcript:
{transcript.text[:12000]}

{'Segment samples (for chapter timing):' + chr(10) + segment_hint if segment_hint else ''}

Generate a JSON object with these fields:
- "titles": array of 3-5 compelling title options
- "summary": 1-2 paragraph summary of the content
- "key_points": array of 5-10 key points/takeaways as bullet strings
- "chapters": array of objects with "timestamp" (MM:SS), "title" fields — aim for 5-8 chapters based on topic shifts
- "youtube_description": a YouTube-ready description (include a brief summary, key topics, and a call-to-action)
- "youtube_tags": array of 10-15 relevant tags for YouTube SEO

Return ONLY valid JSON, no markdown fences."""

        client = OpenAI(api_key=django_settings.OPENAI_API_KEY)
        response = client.chat.completions.create(
            model="gpt-5-mini",  # Session 1103: upgraded from gpt-4o-mini
            messages=[
                {"role": "system", "content": "You are a video content strategist. Generate structured metadata for videos based on their transcripts. Always return valid JSON."},
                {"role": "user", "content": prompt},
            ],
            max_completion_tokens=3000,
        )

        raw_text = response.choices[0].message.content or '{}'
        # Strip markdown fences if present
        if raw_text.startswith('```'):
            raw_text = raw_text.split('\n', 1)[-1].rsplit('```', 1)[0]
        content_pack = json.loads(raw_text)

        # Validate expected keys
        for key in ['titles', 'summary', 'key_points', 'chapters', 'youtube_description', 'youtube_tags']:
            if key not in content_pack:
                content_pack[key] = [] if key != 'summary' and key != 'youtube_description' else ''

        content_pack['video_id'] = str(video_id)
        content_pack['video_title'] = video_title
        content_pack['transcript_id'] = str(transcript.id)
        content_pack['duration_seconds'] = transcript.duration_seconds

        # Resolve workspace for deliverable
        from core.services.deliverable_workspace_resolver import resolve_workspace
        ws, ws_saved = resolve_workspace()

        # Save as Deliverable
        from core.services.deliverable_factory import create_deliverable
        deliverable = create_deliverable(
            title=f"Content Pack: {video_title[:180]}",
            content=json.dumps(content_pack, indent=2),
            agent_name='VideoContentPackAgent',
            category='Video Content',
            deliverable_type='document',
            user=user,
            tags=['video', 'content-pack', 'auto-generated'],
            agent_task=f"Generate content pack for video: {video_title}",
            content_format='json',
            quality_score=0.8,
            confidence_score=0.85,
            preview_content=(content_pack.get('summary', '') or '')[:500],
            workspace=ws,
            is_saved=ws_saved,
        )

        logger.info(f"Content pack generated for video {video_id}: deliverable {deliverable.id}")

        return {
            'ok': True,
            'deliverable_id': str(deliverable.id),
            'video_id': str(video_id),
            'titles': content_pack.get('titles', []),
            'summary': (content_pack.get('summary', '') or '')[:500],
            'chapter_count': len(content_pack.get('chapters', [])),
            'tag_count': len(content_pack.get('youtube_tags', [])),
        }

    except Exception as exc:
        logger.error(f"Content pack generation failed for video {video_id}: {exc}")
        raise


