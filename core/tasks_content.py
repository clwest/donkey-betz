def _impl_content_autonomy_loop():
    """
    Autonomous content pipeline orchestrator.

    Runs as a single Celery beat task that ties together the full pipeline:
    1. Check daily publish budget (throttle)
    2. Gate-to-repair routing: failed gates → targeted fix agents
    3. Publish approved blogs within budget
    4. Report pipeline stats

    Designed to reduce human intervention to zero for content flow.
    """
    from core.models_unified_system import SelfBlog
    from django.db.models import Q
    from datetime import timedelta

    # Session 1088: Budget-aware scheduling preflight
    try:
        from core.services.ops_autopilot import BudgetAwareScheduler
        pf = BudgetAwareScheduler().preflight('core.tasks.content_autonomy_loop')
        if pf['decision'] == 'defer':
            logger.info(f"[ContentAutonomy] Budget preflight: DEFER — {pf['reason']}")
            return {'success': False, 'deferred': True, 'reason': pf['reason']}
    except Exception as _e:
        logger.warning(
            "tasks_content._impl_content_autonomy_loop: swallowed (%s: %s) — degraded",
            type(_e).__name__, _e,
        )

    now = timezone.now()
    today_start = now.replace(hour=0, minute=0, second=0, microsecond=0)

    # ── Config ──
    DAILY_PUBLISH_BUDGET = 8       # Max blogs to publish per day
    MAX_REPAIR_PER_CYCLE = 3       # Max gate-to-repair passes per cycle
    STUCK_THRESHOLD_HOURS = 4      # How long before content is "stuck"

    stats = {
        'published_today': 0,
        'budget_remaining': DAILY_PUBLISH_BUDGET,
        'repairs_attempted': 0,
        'repairs_succeeded': 0,
        'published_this_cycle': 0,
    }

    try:
        # ── Step 1: Check daily budget ──
        published_today = SelfBlog.objects.filter(
            status='published',
            created_at__gte=today_start,
        ).count()
        stats['published_today'] = published_today
        stats['budget_remaining'] = max(0, DAILY_PUBLISH_BUDGET - published_today)

        if stats['budget_remaining'] <= 0:
            logger.info(
                f"[CONTENT-AUTONOMY] Daily publish budget exhausted "
                f"({published_today}/{DAILY_PUBLISH_BUDGET})"
            )
            return stats

        # ── Step 2: Gate-to-repair routing ──
        # Find blogs that failed gate (needs_enhancement with gate_notes)
        stuck_cutoff = now - timedelta(hours=STUCK_THRESHOLD_HOURS)
        repair_candidates = SelfBlog.objects.filter(
            status='needs_enhancement',
            gate_notes__isnull=False,
            created_at__lte=stuck_cutoff,
        ).exclude(
            gate_notes=''
        ).order_by('created_at')[:MAX_REPAIR_PER_CYCLE]

        for blog in repair_candidates:
            try:
                repair_action = _route_gate_repair(blog)
                if repair_action:
                    stats['repairs_attempted'] += 1
                    success = _execute_gate_repair(blog, repair_action)
                    if success:
                        stats['repairs_succeeded'] += 1
            except Exception as e:
                logger.warning(f"[CONTENT-AUTONOMY] Repair failed for {blog.id}: {e}")

        # ── Step 3: Publish approved blogs within budget ──
        approved = SelfBlog.objects.filter(
            status='approved',
            publish_ready=True,
        ).order_by('-quality_score')[:stats['budget_remaining']]

        for blog in approved:
            blog.status = 'published'
            blog.save(update_fields=['status'])
            stats['published_this_cycle'] += 1
            logger.info(f"[CONTENT-AUTONOMY] Published: {blog.title[:60]}")

        if stats['published_this_cycle'] or stats['repairs_attempted']:
            logger.info(
                f"[CONTENT-AUTONOMY] Cycle: published={stats['published_this_cycle']}, "
                f"repairs={stats['repairs_succeeded']}/{stats['repairs_attempted']}, "
                f"budget={stats['budget_remaining'] - stats['published_this_cycle']} remaining"
            )

    except Exception as e:
        logger.error(f"[CONTENT-AUTONOMY] Loop error: {e}")
        stats['error'] = str(e)

    return stats




def _impl_score_episode_voice(episode_id: str):
    """
    Session 784: Score an episode's voice quality using VoiceCriticAgent.

    This is a post-generation step that scores content WITHOUT editing it.
    Scores are stored as metadata for learning - the system learns taste over time.

    Args:
        episode_id: UUID of the ChannelEpisode to score

    Returns:
        dict: Voice scores (distinctiveness, specificity, opinion_strength, generic_flag)
    """
    from core.models_autonomous_studio import ChannelEpisode
    from core.agents.content.voice_critic_agent import get_voice_critic_agent

    logger.info(f"🎭 [VOICE CRITIC] Scoring episode: {episode_id}")

    try:
        episode = ChannelEpisode.objects.get(id=episode_id)

        # Skip if already scored
        if episode.voice_critique_completed:
            logger.info(f"🎭 [VOICE CRITIC] Episode {episode_id} already scored, skipping")
            return {
                'success': True,
                'already_scored': True,
                'episode_id': episode_id
            }

        # Get content to score
        content = episode.script or episode.description
        if not content:
            logger.warning(f"🎭 [VOICE CRITIC] Episode {episode_id} has no content to score")
            return {
                'success': False,
                'error': 'No content to score',
                'episode_id': episode_id
            }

        # Score with VoiceCriticAgent
        agent = get_voice_critic_agent()
        result = agent.execute(
            task=f"Score voice quality for: {episode.title}",
            context={
                'content': content,
                'title': episode.title,
                'content_type': 'blog_post',
            },
            scifi_context={},
            spider_context={}
        )

        if result.success:
            scores = result.data.get('voice_scores', {})

            # Update episode with scores
            episode.distinctiveness_score = scores.get('distinctiveness_score', 0)
            episode.specificity_score = scores.get('specificity_score', 0)
            episode.opinion_strength_score = scores.get('opinion_strength_score', 0)
            episode.generic_flag = scores.get('generic_flag', False)
            episode.intent_type = scores.get('intent_type', '')
            episode.voice_critique_completed = True
            episode.save(update_fields=[
                'distinctiveness_score', 'specificity_score',
                'opinion_strength_score', 'generic_flag',
                'intent_type', 'voice_critique_completed'
            ])

            logger.info(
                f"🎭 [VOICE CRITIC] Scored episode {episode_id}: "
                f"D={scores.get('distinctiveness_score')}, "
                f"S={scores.get('specificity_score')}, "
                f"O={scores.get('opinion_strength_score')}, "
                f"Generic={scores.get('generic_flag')}, "
                f"Intent={scores.get('intent_type')}"
            )

            return {
                'success': True,
                'episode_id': episode_id,
                'title': episode.title,
                'scores': scores
            }
        else:
            logger.error(f"🎭 [VOICE CRITIC] Failed to score episode {episode_id}: {result.error}")
            return {
                'success': False,
                'episode_id': episode_id,
                'error': result.error
            }

    except ChannelEpisode.DoesNotExist:
        logger.error(f"🎭 [VOICE CRITIC] Episode {episode_id} not found")
        return {
            'success': False,
            'episode_id': episode_id,
            'error': 'Episode not found'
        }
    except Exception as e:
        logger.error(f"🎭 [VOICE CRITIC] Error scoring episode {episode_id}: {e}")
        return {
            'success': False,
            'episode_id': episode_id,
            'error': str(e)
        }




