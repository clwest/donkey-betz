def _impl_generate_self_blog_deliberation_task(self, tone='enthusiastic', word_count=1500, topic_category=None):
    """
    Phase 4: Generate a blog through the multi-agent deliberation pipeline.

    Same signature as generate_self_blog_task but uses ContentDeliberationRunner
    for ClaimsPack -> Draft -> 3-reviewer panel -> DecisionEnforcer -> PublishGate.

    Session 1062: Added Redis lock (max_concurrency=1) to prevent OOM from
    concurrent deliberation tasks crashing celery-content every hour.

    Session 1064: Increased soft_time_limit 240→480s and time_limit 300→540s
    to prevent zero-turn failures. Full pipeline (ClaimsPack + draft + review
    + 4 conversation turns) routinely needs 180-480s.

    Args:
        tone: Blog tone
        word_count: Target word count
        topic_category: Topic source ('trending', 'dreams', 'conversations', 'system', 'random')
    """
    import random
    from datetime import timedelta
    from django.utils import timezone

    # Session 1062: Only one deliberation at a time — prevents OOM on celery-content
    from django.core.cache import cache
    lock_key = 'deliberation_blog_running'
    if not cache.add(lock_key, self.request.id, timeout=300):
        logger.info(f"[Phase 4] Skipping deliberation — another is already running (lock={lock_key})")
        return {'success': False, 'skipped': True, 'reason': 'concurrent deliberation already running'}

    # Session 1088: Budget-aware scheduling preflight
    try:
        from core.services.ops_autopilot import BudgetAwareScheduler
        pf = BudgetAwareScheduler().preflight('core.tasks.generate_self_blog_deliberation_task')
        if pf['decision'] == 'defer':
            cache.delete(lock_key)
            logger.info(f"[Phase 4] Budget preflight: DEFER — {pf['reason']}")
            return {'success': False, 'deferred': True, 'reason': pf['reason']}
    except Exception as _e:
        logger.warning(
            "tasks_content._impl_generate_self_blog_deliberation_task: swallowed (%s: %s) — degraded",
            type(_e).__name__, _e,
        )

    # Session 969: Weight away from 'system' for diversity
    if topic_category is None or topic_category == 'random':
        topic_category = random.choice(['trending', 'trending', 'dreams', 'conversations'])

    logger.info(f"[Phase 4] Starting deliberation blog: tone={tone}, category={topic_category}")

    try:
        blog_topic = None  # Session 969: No hardcoded default — use fallback pool

        if topic_category == 'trending':
            try:
                from core.models_unified_system import SpiderData
                now = timezone.now()
                recent = SpiderData.objects.filter(
                    created_at__gte=now - timedelta(hours=48)
                ).order_by('-created_at')[:20]
                for entry in recent:
                    raw = entry.raw_data
                    if isinstance(raw, str):
                        import json
                        try:
                            raw = json.loads(raw)
                        except Exception:
                            continue
                    if isinstance(raw, dict):
                        items = raw.get('items', [])
                        for item in items:
                            title = item.get('title', '')
                            if title and len(title) > 15:
                                blog_topic = title[:100]
                                break
                    if blog_topic:
                        break
            except Exception as e:
                logger.warning(f"[Phase 4] Trending topic fetch failed: {e}")

        elif topic_category == 'system':
            pass  # Session 969: Fall through to diversified fallback below

        elif topic_category == 'dreams':
            try:
                from core.models_unified_system import AgentDream
                dream = AgentDream.objects.order_by('-dreamed_at').first()
                if dream and dream.title:
                    blog_topic = dream.title[:100]
            except Exception as e:
                logger.warning(f"📝 [BLOG] Dream topic extraction failed: {e}")

        elif topic_category == 'conversations':
            try:
                from core.models_unified_system import AgentConversation
                convo = AgentConversation.objects.order_by('-started_at').first()
                if convo and convo.topic:
                    blog_topic = convo.topic[:100]
            except Exception as e:
                logger.warning(f"📝 [BLOG] Conversation topic extraction failed: {e}")

        # Session 1076: Sanitize topic to prevent malformed strings from
        # crashing the deliberation pipeline (e.g. "hivemind:," → empty turns)
        if blog_topic:
            import re as _re
            blog_topic = blog_topic.strip()
            blog_topic = _re.sub(r'[:;,.\-]+$', '', blog_topic).strip()  # strip trailing punctuation
            blog_topic = _re.sub(r':{2,}', ':', blog_topic)  # collapse :: → :
            blog_topic = _re.sub(r',{2,}', ',', blog_topic)  # collapse ,, → ,
            # If after sanitization it's too short, discard it
            if len(blog_topic) < 12:
                logger.warning(f"[Phase 4] Topic too short after sanitization ({blog_topic!r}), using fallback")
                blog_topic = None

        # Session 969: Diversified fallback when no topic was found
        if not blog_topic:
            _v2_fallback_topics = [
                'How Smart Contract Auditing Is Evolving in 2026',
                'The Rise of Prediction Markets and What They Tell Us',
                'Why Sports Analytics Is the New Edge in Betting',
                'Building AI-Assisted Software: Lessons from the Trenches',
                'The Legal Tech Revolution Nobody Is Talking About',
                'Career Pivots in the Age of AI: What Actually Works',
                'What On-Chain Data Reveals About Whale Behavior',
                'The Next Wave of Open Source AI Models',
                'How Autonomous Systems Learn From Their Mistakes',
                'Market Signals: Reading Between the Headlines',
            ]
            blog_topic = random.choice(_v2_fallback_topics)
            logger.info(f"[Phase 4] Using diversified fallback topic: {blog_topic}")

        from core.services.content_deliberation_runner import ContentDeliberationRunner
        runner = ContentDeliberationRunner()
        result = runner.run_blog(topic=blog_topic, voice=tone)

        logger.info(
            f"[Phase 4] Deliberation complete: status={result['status']}, "
            f"decision={result['decision']}, blog={result['selfblog_id']}"
        )
        return {
            'success': result['selfblog_id'] is not None,
            'blog_id': result['selfblog_id'],
            'status': result['status'],
            'decision': result['decision'],
            'deliberation_session_id': result['deliberation_session_id'],
            'summary': result['summary'],
        }

    except SoftTimeLimitExceeded:
        logger.error(f"[Phase 4] Deliberation TIMEOUT: topic={blog_topic!r}")
        # Tag any in-flight deliberation session with TIMEOUT reason code
        try:
            from core.models_deliberation import DeliberationSession
            recent = DeliberationSession.objects.filter(
                status='active', created_at__gte=timezone.now() - timedelta(minutes=10)
            ).order_by('-created_at').first()
            if recent:
                recent.status = 'failed'
                recent.failure_reason_code = 'TIMEOUT'
                recent.failure_detail = f'SoftTimeLimitExceeded (480s) during topic: {blog_topic!r}'
                recent.completed_at = timezone.now()
                recent.save(update_fields=[
                    'status', 'failure_reason_code', 'failure_detail',
                    'completed_at', 'updated_at',
                ])
                logger.info(f"[Phase 4] Tagged session {recent.id} with TIMEOUT reason code")
        except Exception as tag_err:
            logger.warning(f"[Phase 4] Failed to tag timeout session: {tag_err}")
        return {'success': False, 'error': 'SoftTimeLimitExceeded', 'timed_out': True}

    except Exception as e:
        logger.error(f"[Phase 4] Deliberation task failed: {e}", exc_info=True)
        # Classify the failure reason using expanded pattern matcher
        from core.models_deliberation import classify_failure_reason
        reason_code = classify_failure_reason(str(e))
        try:
            from core.models_deliberation import DeliberationSession
            recent = DeliberationSession.objects.filter(
                status='active', created_at__gte=timezone.now() - timedelta(minutes=10)
            ).order_by('-created_at').first()
            if recent:
                recent.status = 'failed'
                recent.failure_reason_code = reason_code
                recent.failure_detail = str(e)[:500]
                recent.completed_at = timezone.now()
                recent.save(update_fields=[
                    'status', 'failure_reason_code', 'failure_detail',
                    'completed_at', 'updated_at',
                ])
        except Exception as _e:
            logger.warning(
                "tasks_content._impl_generate_self_blog_deliberation_task: swallowed (%s: %s) — degraded",
                type(_e).__name__, _e,
            )
        return {'success': False, 'error': str(e), 'failure_reason_code': reason_code}

    finally:
        cache.delete(lock_key)


