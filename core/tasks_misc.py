def _impl_process_pa_chat_task(self, user_id, message, context=None, generate_audio=False, conversation_id=None, source='web', platform='web'):
    """
    Session 974b: Async PA chat processing to avoid Railway proxy timeouts.
    Runs UnifiedPAEntrypoint in Celery worker, stores result in Redis via Celery result backend.
    """
    import asyncio
    from django.contrib.auth import get_user_model

    User = get_user_model()
    user = User.objects.get(id=user_id)

    # Session 1085: Resolve conversation_id BEFORE PA init so history is scoped
    from core.models import ChatConversation
    if not conversation_id:
        conversation_id, _ = ChatConversation.get_or_create_session(user=user, platform=platform)

    # Session 1068: Create fresh PA instance per task instead of caching.
    from core.services.unified_pa_entrypoint import UnifiedPAEntrypoint
    pa = UnifiedPAEntrypoint(user, conversation_id=conversation_id)

    start_ms = time.time()
    # Session 976: Run async PA in a fresh event loop to avoid deadlock
    # in Celery's --pool=threads worker. async_to_sync and asyncio.run()
    # can both fail if an event loop already exists in the thread.
    # Session 1077: NEVER generate audio in the main task — it blocks for
    # 60-280s calling ElevenLabs TTS and causes SoftTimeLimitExceeded.
    # Audio is generated in a separate background task after the response.
    loop = asyncio.new_event_loop()
    try:
        response = loop.run_until_complete(pa.process_message(
            message=message,
            context=context or {},
            generate_audio=False  # Always False — TTS offloaded below
        ))
    finally:
        loop.close()
    elapsed_ms = int((time.time() - start_ms) * 1000)

    # Persist to ChatConversation (same logic as the former sync view)
    try:
        is_first = not ChatConversation.objects.filter(conversation_id=conversation_id).exists()

        # Session 1063: Sanitize metadata — tool results may contain UUIDs,
        # datetimes, or other non-JSON-serializable objects from agent execution.
        raw_metadata = {
            'trace_id': response.trace_id,
            'intent': response.intent,
            'routed_to': response.routed_to,
            # Session 1036: Persist function calling metadata for multi-turn context
            'tool_calls': response.tool_call_metadata or [],
            'tool_results': response.tool_result_data or [],
            'response_id': response.response_id,
            'source': source,
        }
        # Session 1100: Persist conversation lane in metadata
        if getattr(response, 'lane', None):
            raw_metadata['lane'] = response.lane
        metadata = json.loads(json.dumps(raw_metadata, default=str))

        # Resolve workspace for conversation binding
        conv_workspace = None
        ctx = context or {}
        ws_id = ctx.get('workspace_id')
        if ws_id:
            try:
                from core.models_skin_layer import ProjectWorkspace
                conv_workspace = ProjectWorkspace.objects.filter(id=ws_id).first()
            except Exception:
                pass
        # Also check if this conversation already has a workspace binding
        if not conv_workspace:
            existing = ChatConversation.objects.filter(
                conversation_id=conversation_id, workspace__isnull=False
            ).values_list('workspace_id', flat=True).first()
            if existing:
                try:
                    from core.models_skin_layer import ProjectWorkspace
                    conv_workspace = ProjectWorkspace.objects.filter(id=existing).first()
                except Exception:
                    pass

        chat_row = ChatConversation.objects.create(
            user=user,
            conversation_id=conversation_id,
            user_message=message,
            assistant_response=response.content or '',
            platform=platform,
            source=source,  # Session 1074: Collaboration protocol actor tracking
            workspace=conv_workspace,
            metadata=metadata,
            response_time_ms=response.latency_ms or elapsed_ms,
            agents_used=[r.get('tool', '') for r in (response.tool_runs or [])],
        )

        if is_first:
            chat_row.generate_session_title()

        # Broadcast to WebSocket for real-time 3-way chat
        try:
            from channels.layers import get_channel_layer
            from asgiref.sync import async_to_sync
            channel_layer = get_channel_layer()
            if channel_layer:
                group = f"pa_conversation_{conversation_id}"
                ctx = context or {}
                # Only broadcast user message if NOT already stored by store-only endpoint
                if not ctx.get('already_stored'):
                    async_to_sync(channel_layer.group_send)(group, {
                        "type": "message.created",
                        "message": {
                            "id": str(chat_row.id),
                            "role": "user",
                            "content": message,
                            "source": source,
                            "timestamp": chat_row.created_at.isoformat(),
                        }
                    })
                # Always broadcast Rigby's response
                if response.content:
                    async_to_sync(channel_layer.group_send)(group, {
                        "type": "message.created",
                        "message": {
                            "id": f"{chat_row.id}-response",
                            "role": "assistant",
                            "content": response.content,
                            "source": "pa",
                            "tools_used": [r.get('tool', '') for r in (response.tool_runs or [])],
                            "timestamp": chat_row.created_at.isoformat(),
                        }
                    })
        except Exception as ws_err:
            logger.debug(f"WebSocket broadcast failed (non-critical): {ws_err}")

    except Exception as persist_err:
        logger.warning(f"Failed to persist PA conversation: {persist_err}")

    # NOTE: Claude Code agent dispatch moved to view level (unified_pa_chat)
    # to ensure it fires reliably before PA task processing.
    # Do NOT dispatch from here to avoid double-dispatch.

    # Session 1077: Offload TTS to background task if audio was requested
    audio_url = response.audio_url  # Will be None since we forced generate_audio=False
    if generate_audio and response.content:
        try:
            from core.tasks import process_pa_tts_task
            process_pa_tts_task.delay(
                user_id=user_id,
                text=response.content[:5000],  # Cap TTS input
                conversation_id=conversation_id,
                trace_id=response.trace_id,
            )
            logger.info(f"[PA_TTS] Dispatched background TTS for conversation {conversation_id}")
        except Exception as tts_err:
            logger.warning(f"[PA_TTS] Failed to dispatch TTS task: {tts_err}")

    # Session 1076+: Sanitize entire return dict — tool_runs may contain
    # non-JSON-serializable objects (ManyRelatedManager, UUID, ProjectWorkspace)
    # that cause EncodeError in Celery's JSON serializer.
    raw_return = {
        'success': True,
        'content': response.content,
        'trace_id': response.trace_id,
        'tool_runs': response.tool_runs,
        'audio_url': audio_url,
        'intent': response.intent,
        'routed_to': response.routed_to,
        'profile_completeness': response.profile_completeness,
        'latency_ms': response.latency_ms,
        'error': response.error,
        'conversation_id': conversation_id,
        'source': source,
    }
    return json.loads(json.dumps(raw_return, default=str))


