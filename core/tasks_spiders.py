def _impl_run_spider_by_category(self, category: str, execution_mode: str = 'interactive'):
    """
    Run spiders for a specific category.

    Session 265 Phase 6: Used by autonomy engine for spider dispatch.
    Session 484: Added SpiderExecutionLog for tracking.
    Session 1076: execution_mode='scheduled' raises on total failure (visible to SLO/signatures).
                  execution_mode='interactive' returns error dicts (UI-safe).
    """
    from ai_core.spiders.spider_registry import SpiderRegistry
    from core.models_unified_system import SpiderExecutionLog
    import traceback

    try:
        registry = SpiderRegistry()
        spiders = registry.get_spiders_by_category(category)

        results = []
        failures = []
        spider_names = list(spiders.keys())[:3] if isinstance(spiders, dict) else list(spiders)[:3]
        for spider_name in spider_names:  # Limit to 3 spiders per category
            # Session 484: Create execution log
            execution_log = SpiderExecutionLog.start_execution(
                spider_name=spider_name,
                category=category,
                triggered_by='scheduled' if execution_mode == 'scheduled' else 'on_demand',
                celery_task_id=self.request.id if self.request else None
            )
            spider_start_time = time.time()

            try:
                spider_class = registry.get_spider_class(spider_name)
                if spider_class:
                    spider = _create_spider_instance(spider_class, spider_name)
                    data = _run_spider_adapter(spider, spider_name)

                    item_count = len(data) if isinstance(data, list) else len(data.get('items', []) if isinstance(data, dict) else [])
                    results.append({
                        'spider': spider_name,
                        'items': item_count,
                    })
                    # Session 484: Mark success
                    execution_log.complete_success(
                        items_collected=item_count,
                        duration_seconds=time.time() - spider_start_time
                    )
            except Exception as spider_error:
                logger.warning(f"Spider {spider_name} failed: {spider_error}")
                failures.append({'spider': spider_name, 'error': str(spider_error)})
                # Session 484: Mark error
                execution_log.complete_error(
                    error_message=str(spider_error),
                    error_type=type(spider_error).__name__,
                    error_traceback=traceback.format_exc(),
                    duration_seconds=time.time() - spider_start_time
                )

        logger.info(f"Ran {len(results)} spiders for category {category} ({len(failures)} failed)")

        # Session 1076: If ALL spiders failed in scheduled mode, raise so Celery marks FAILURE
        if execution_mode == 'scheduled' and failures and not results:
            error_summary = '; '.join(f['error'][:80] for f in failures[:3])
            raise RuntimeError(
                f"All {len(failures)} spiders failed for category '{category}': {error_summary}"
            )

        return {'category': category, 'results': results, 'failures': failures}

    except RuntimeError:
        raise  # Re-raise the explicit failure from above
    except Exception as e:
        logger.error(f"Spider dispatch failed for {category}: {e}")
        if execution_mode == 'scheduled':
            raise  # Fail loudly — visible to SLO/failure signatures
        return {'error': str(e)}




def _impl_execute_single_spider(self, spider_name: str, execution_log_id: str = None):
    """
    Session 484: Execute a single spider with full execution logging.
    Used by manual UI runs and retry operations.
    """
    from ai_core.spiders.spider_registry import SpiderRegistry
    from ai_core.spiders.real_data_collector import collect_spider_data_sync, SPIDER_TARGET_URLS
    from core.models_unified_system import SpiderData, SpiderExecutionLog
    import traceback

    spider_start_time = time.time()
    execution_log = None
    source_urls = []

    try:
        # Get or create execution log
        if execution_log_id:
            try:
                execution_log = SpiderExecutionLog.objects.get(id=execution_log_id)
                execution_log.celery_task_id = self.request.id if self.request else None
                execution_log.save()
            except SpiderExecutionLog.DoesNotExist:
                pass

        if not execution_log:
            # Find most recent running log for this spider
            execution_log = SpiderExecutionLog.objects.filter(
                spider_name=spider_name,
                status='running',
                celery_task_id__isnull=True
            ).order_by('-started_at').first()

            if execution_log:
                execution_log.celery_task_id = self.request.id if self.request else None
                execution_log.save()

        logger.info(f"🕷️ Executing single spider: {spider_name}")

        # Get spider info
        registry = SpiderRegistry()
        spider_config = registry.list_spiders().get(spider_name, {})
        config = spider_config.get('config', {})
        category = config.get('category', spider_config.get('category', 'general'))

        # Execute spider
        if spider_name in SPIDER_TARGET_URLS:
            source_urls = SPIDER_TARGET_URLS.get(spider_name, [])
            data = collect_spider_data_sync(spider_name)
            item_count = data.get('item_count', 0)
        else:
            spider_class = registry.get_spider_class(spider_name)
            if spider_class:
                spider = _create_spider_instance(spider_class, spider_name)
                data = _run_spider_adapter(spider, spider_name)
                # Handle both list and dict formats
                if isinstance(data, list):
                    item_count = len(data)
                    data = {'items': data, 'source': spider_name}
                else:
                    item_count = len(data.get('items', []))
            else:
                data = {'items': [], 'error': f'Spider class not found: {spider_name}'}
                item_count = 0

        # Session 616: Item-level deduplication
        from core.services.spider_deduplication import deduplicate_spider_items

        items = data.get('items', []) if isinstance(data, dict) else []
        unique_items, dedup_stats = deduplicate_spider_items(spider_name, items, category)

        # Only save if there are unique items
        if unique_items:
            # Update data with only unique items
            if isinstance(data, dict):
                data['items'] = unique_items
                data['dedup_stats'] = dedup_stats

            spider_data = SpiderData.objects.create(
                spider_name=spider_name,
                data_type=category,
                raw_data=data if isinstance(data, dict) else {'data': str(data)},
                source_url=source_urls[0] if source_urls else 'manual',
                relevance_score=70 if len(unique_items) > 0 else 30
            )
            item_count = len(unique_items)
            logger.info(f"✅ Spider {spider_name} completed: {item_count} unique items (dedup: {dedup_stats['duplicates']} removed)")
        else:
            # No unique items - skip creating SpiderData record
            spider_data = None
            item_count = 0
            logger.info(f"⏭️ Spider {spider_name}: all {dedup_stats['total']} items already seen, skipping save")

        # Update execution log
        if execution_log:
            execution_log.source_urls_attempted = source_urls if source_urls else ['manual']
            execution_log.complete_success(
                items_collected=item_count,
                duration_seconds=time.time() - spider_start_time
            )

        return {
            'spider': spider_name,
            'success': True,
            'item_count': item_count,
            'data_id': str(spider_data.id) if spider_data else None,
            'dedup_stats': dedup_stats,  # Session 616: Include dedup stats
        }

    except Exception as e:
        logger.error(f"❌ Spider {spider_name} failed: {e}")

        # Update execution log with error
        if execution_log:
            execution_log.source_urls_attempted = source_urls if source_urls else []
            execution_log.complete_error(
                error_message=str(e),
                error_type=type(e).__name__,
                error_traceback=traceback.format_exc(),
                duration_seconds=time.time() - spider_start_time
            )

        return {
            'spider': spider_name,
            'success': False,
            'error': str(e),
        }




def _impl_process_core_spider_data():
    """
    Session 707: Process unprocessed spider data from core.models_unified_system.SpiderData

    This task processes the CORE SpiderData table which is used by the unified system,
    as opposed to the legacy persistence.models.SpiderData table.

    The DIGESTIVE system monitors this table for queue depth.

    Runs every 2 minutes with 500 items per batch to catch up with backlog.
    """
    from core.models_unified_system import SpiderData
    from intelligence.spider_agent_connector import SpiderAgentConnector
    from django.utils import timezone

    logger.info("🍽️ [DIGESTIVE] Starting core spider data processing...")

    connector = SpiderAgentConnector()

    # Get unprocessed spider data (50 per run — still 1,500/hour at 2-min interval)
    unprocessed = SpiderData.objects.filter(is_processed=False).defer('embedding').order_by('created_at')[:50]
    total_unprocessed = SpiderData.objects.filter(is_processed=False).defer('embedding').count()

    results = {
        'processed': 0,
        'solutions_created': 0,
        'learning_records': 0,
        'errors': 0,
        'agents_matched': 0,
        'remaining': total_unprocessed
    }

    if not unprocessed:
        logger.info("🍽️ [DIGESTIVE] No unprocessed spider data found")
        return results

    logger.info(f"🍽️ [DIGESTIVE] Processing {len(unprocessed)} of {total_unprocessed} unprocessed items...")

    for spider_data in unprocessed:
        try:
            # Route spider data to agents
            result = connector.route_spider_data(spider_data)

            # Mark as processed with timestamp
            spider_data.is_processed = True
            spider_data.processed_at = timezone.now()
            spider_data.save(update_fields=['is_processed', 'processed_at'])

            results['processed'] += 1
            results['solutions_created'] += len(result.get('solutions_created', []))
            results['learning_records'] += len(result.get('learning_records', []))
            results['agents_matched'] += len(result.get('matched_agents', []))

        except Exception as e:
            results['errors'] += 1
            logger.error(f"Error processing core spider data {spider_data.id}: {e}")
            # Still mark as processed to avoid infinite retry on bad data
            try:
                spider_data.is_processed = True
                spider_data.processed_at = timezone.now()
                spider_data.save(update_fields=['is_processed', 'processed_at'])
            except Exception as e:
                logger.warning(f"Failed to mark spider_data {spider_data.id} as processed: {e}")

    results['remaining'] = total_unprocessed - results['processed']

    logger.info(f"✅ [DIGESTIVE] Core processing complete: {results['processed']} items processed")
    logger.info(f"   Solutions: {results['solutions_created']}, Learning: {results['learning_records']}")
    logger.info(f"   Agents matched: {results['agents_matched']}, Errors: {results['errors']}")
    logger.info(f"   Remaining in queue: {results['remaining']}")

    return results




