def _impl_snapshot_odds_for_line_movement():
    """
    Session 561: Capture current odds for line movement tracking.

    Runs every 20 minutes to build historical odds data for line movement charts.
    Captures all major sports from The Odds API and stores snapshots.
    """
    from core.models_odds_history import OddsSnapshot, GameLineHistory
    from ai_core.spiders.specialized.theodds_spider import TheOddsSpider
    from django.utils import timezone
    from decimal import Decimal

    logger.info("📊 [ODDS-SNAPSHOT] Starting odds snapshot collection...")

    try:
        spider = TheOddsSpider()

        # Sports to track
        sports_list = ['americanfootball_nfl', 'basketball_nba', 'icehockey_nhl', 'baseball_mlb']

        total_snapshots = 0
        games_updated = 0

        # Fetch all sports at once (API efficient)
        try:
            odds_data = spider.fetch_data(sports=sports_list, include_futures=False, max_results=100)
        except Exception as e:
            logger.warning(f"📊 [ODDS-SNAPSHOT] Spider error: {e}")
            odds_data = []

        for game in odds_data:
            try:
                # Use event_id from normalized spider data
                game_id = game.get('event_id')
                # Skip status records and games without IDs
                if not game_id or game.get('data_type') == 'api_status':
                    continue

                sport = game.get('sport_key', 'unknown')
                home_team = game.get('home_team', '')
                away_team = game.get('away_team', '')
                commence_time = game.get('commence_time')
                bookmaker = game.get('best_bookmaker', 'consensus')

                # Parse commence_time if it's a string
                if isinstance(commence_time, str):
                    from dateutil import parser
                    commence_time = parser.parse(commence_time)

                # Create snapshots from normalized odds data
                # Moneyline (h2h)
                if game.get('home_odds'):
                    OddsSnapshot.objects.create(
                        game_id=game_id,
                        sport_key=sport,
                        home_team=home_team,
                        away_team=away_team,
                        commence_time=commence_time,
                        bookmaker=bookmaker,
                        bookmaker_title=bookmaker,
                        market='h2h',
                        outcome_name=home_team,
                        price=int(game.get('home_odds', 0)),
                    )
                    total_snapshots += 1
                if game.get('away_odds'):
                    OddsSnapshot.objects.create(
                        game_id=game_id,
                        sport_key=sport,
                        home_team=home_team,
                        away_team=away_team,
                        commence_time=commence_time,
                        bookmaker=bookmaker,
                        bookmaker_title=bookmaker,
                        market='h2h',
                        outcome_name=away_team,
                        price=int(game.get('away_odds', 0)),
                    )
                    total_snapshots += 1

                # Spreads
                if game.get('home_spread'):
                    spread_data = game.get('spread', {})
                    OddsSnapshot.objects.create(
                        game_id=game_id,
                        sport_key=sport,
                        home_team=home_team,
                        away_team=away_team,
                        commence_time=commence_time,
                        bookmaker=bookmaker,
                        bookmaker_title=bookmaker,
                        market='spreads',
                        outcome_name=home_team,
                        price=int(spread_data.get('home_price', -110)),
                        point=Decimal(str(game.get('home_spread', 0))),
                    )
                    total_snapshots += 1

                # Totals
                if game.get('total_line'):
                    OddsSnapshot.objects.create(
                        game_id=game_id,
                        sport_key=sport,
                        home_team=home_team,
                        away_team=away_team,
                        commence_time=commence_time,
                        bookmaker=bookmaker,
                        bookmaker_title=bookmaker,
                        market='totals',
                        outcome_name='Over',
                        price=int(game.get('over_odds', -110)),
                        point=Decimal(str(game.get('total_line', 0))),
                    )
                    total_snapshots += 1

                # Update or create GameLineHistory summary
                history, created = GameLineHistory.objects.get_or_create(
                    game_id=game_id,
                    defaults={
                        'sport_key': sport,
                        'home_team': home_team,
                        'away_team': away_team,
                        'commence_time': commence_time,
                    }
                )

                # Update tracking
                now = timezone.now()
                if created:
                    history.first_snapshot_at = now
                    # Set opening lines from first snapshot
                    history.open_ml_home = game.get('home_odds')
                    history.open_ml_away = game.get('away_odds')
                    if game.get('home_spread'):
                        history.open_spread_home = Decimal(str(game.get('home_spread', 0)))
                    if game.get('total_line'):
                        history.open_total = Decimal(str(game.get('total_line', 0)))

                # Always update current lines and last snapshot time
                history.last_snapshot_at = now
                history.snapshot_count = (history.snapshot_count or 0) + 1

                # Update current lines
                history.current_ml_home = game.get('home_odds')
                history.current_ml_away = game.get('away_odds')
                if game.get('home_spread'):
                    history.current_spread_home = Decimal(str(game.get('home_spread', 0)))
                if game.get('total_line'):
                    history.current_total = Decimal(str(game.get('total_line', 0)))

                # Calculate movement
                if history.open_spread_home and history.current_spread_home:
                    history.spread_movement = history.current_spread_home - history.open_spread_home
                if history.open_total and history.current_total:
                    history.total_movement = history.current_total - history.open_total

                history.save()
                games_updated += 1

            except Exception as e:
                logger.warning(f"📊 [ODDS-SNAPSHOT] Error processing game: {e}")
                continue

        logger.info(f"📊 [ODDS-SNAPSHOT] Complete: {total_snapshots} snapshots, {games_updated} games")
        return {
            'success': True,
            'snapshots': total_snapshots,
            'games': games_updated,
            'timestamp': timezone.now().isoformat(),
        }

    except Exception as e:
        logger.error(f"📊 [ODDS-SNAPSHOT] Failed: {e}", exc_info=True)
        return {
            'success': False,
            'error': str(e)
        }




def _impl_evaluate_ml_predictions(self):
    """
    Session 995B: Evaluate past ML predictions against actual outcomes.

    Checks stored MLPrediction records where the game has completed,
    compares predicted winner to actual winner, and records accuracy.
    """
    from django.utils import timezone
    from datetime import timedelta

    logger.info("[ML-EVAL] Starting ML prediction evaluation...")

    try:
        from sports.models import MLPrediction
        from ai_core.spiders.specialized.theodds_spider import TheOddsSpider

        spider = TheOddsSpider()
        now = timezone.now()
        cutoff = now - timedelta(hours=72)

        # Find unevaluated predictions from last 3 days
        pending = MLPrediction.objects.filter(
            evaluated=False,
            created_at__gte=cutoff,
        ) if hasattr(MLPrediction, 'evaluated') else MLPrediction.objects.none()

        if not pending.exists():
            logger.info("[ML-EVAL] No pending predictions to evaluate")
            return {'status': 'success', 'evaluated': 0}

        # Group by sport for batch score fetching
        sport_keys = set()
        for pred in pending:
            if hasattr(pred, 'sport_key') and pred.sport_key:
                sport_keys.add(pred.sport_key)

        # Fetch scores for each sport
        all_scores = {}
        for sport_key in sport_keys:
            try:
                scores = spider.fetch_scores(sport_key=sport_key, days_from=3)
                for s in scores:
                    all_scores[s['event_id']] = s
            except Exception as e:
                logger.warning(f"[ML-EVAL] Score fetch failed for {sport_key}: {e}")

        # Evaluate each prediction
        evaluated = 0
        correct = 0
        for pred in pending:
            event_id = pred.event_id if hasattr(pred, 'event_id') else None
            if not event_id or event_id not in all_scores:
                continue

            score = all_scores[event_id]
            home_score = score.get('home_score', 0)
            away_score = score.get('away_score', 0)

            actual_winner = 'home' if home_score > away_score else 'away'
            predicted = pred.predicted_winner if hasattr(pred, 'predicted_winner') else ''

            # Normalize: check if predicted team matches home or away
            is_correct = False
            home_team = score.get('home_team', '')
            away_team = score.get('away_team', '')

            if predicted.lower() in home_team.lower() and actual_winner == 'home':
                is_correct = True
            elif predicted.lower() in away_team.lower() and actual_winner == 'away':
                is_correct = True

            if hasattr(pred, 'evaluated'):
                pred.evaluated = True
            if hasattr(pred, 'was_correct'):
                pred.was_correct = is_correct
            if hasattr(pred, 'actual_home_score'):
                pred.actual_home_score = home_score
            if hasattr(pred, 'actual_away_score'):
                pred.actual_away_score = away_score
            pred.save()

            evaluated += 1
            if is_correct:
                correct += 1

        accuracy = round((correct / evaluated) * 100, 1) if evaluated > 0 else 0

        logger.info(
            f"[ML-EVAL] Evaluated {evaluated} predictions: "
            f"{correct} correct ({accuracy}% accuracy)"
        )
        return {
            'status': 'success',
            'evaluated': evaluated,
            'correct': correct,
            'accuracy': accuracy,
        }

    except Exception as e:
        logger.error(f"[ML-EVAL] Failed: {e}", exc_info=True)
        raise self.retry(exc=e)




def _impl_evaluate_and_complete_pilots():
    """
    Session 618: Comprehensive pilot evaluation and learning extraction.

    This task solves the problem of pilots stuck in 'running' state by:
    1. Evaluating pilot outcomes based on simulated progress and decision context
    2. Completing pilots with appropriate outcomes (success/partial/failure)
    3. Updating linked experiments with final results
    4. Extracting learnings from completed experiments
    5. Feeding learnings to collective intelligence

    Schedule: Run every 2 hours via Celery Beat.

    Returns:
        dict with evaluation and learning results
    """
    from django.utils import timezone
    from datetime import timedelta
    import random

    logger.info("🎯 [SESSION 618] Starting pilot evaluation and learning pipeline...")

    try:
        from core.models_pilot_readiness import (
            PilotExecution, Experiment, ExperimentLearning,
            DecisionTypeSuccessPattern
        )

        now = timezone.now()

        # Configuration - accelerated for testing (normally would be 24-48 hours)
        MIN_HOURS_FOR_COMPLETION = 1  # Minimum 1 hour running before eligible

        # Find pilots eligible for completion
        cutoff = now - timedelta(hours=MIN_HOURS_FOR_COMPLETION)
        eligible_pilots = PilotExecution.objects.filter(
            status='running',
            started_at__lte=cutoff,
            outcome='pending'
        ).select_related('gate', 'gate__decision')

        logger.info(f"🎯 [SESSION 618] Found {eligible_pilots.count()} pilots eligible for evaluation")

        results = {
            'evaluated': 0,
            'completed_success': 0,
            'completed_partial': 0,
            'completed_failure': 0,
            'experiments_updated': 0,
            'learnings_created': 0,
            'patterns_updated': 0,
        }

        completed_pilots = []
        created_learnings = []

        for pilot in eligible_pilots:
            try:
                gate = pilot.gate
                decision = gate.decision if gate else None

                if not decision:
                    logger.warning(f"🎯 [SESSION 618] Pilot {pilot.id} has no decision, skipping")
                    continue

                # Calculate outcome based on decision characteristics
                outcome, confidence, reasoning = _evaluate_pilot_outcome(pilot, decision)

                hours_running = (now - pilot.started_at).total_seconds() / 3600

                # Complete the pilot
                pilot.status = 'completed'
                pilot.outcome = outcome
                pilot.outcome_summary = reasoning
                pilot.completed_at = now
                pilot.learnings = [{
                    'type': 'session_618_evaluation',
                    'outcome': outcome,
                    'confidence': confidence,
                    'hours_running': round(hours_running, 1),
                    'decision_type': decision.decision_type,
                    'impact_area': decision.impact_area,
                }]
                pilot.save()

                # Update gate
                gate.complete_pilot()

                results['evaluated'] += 1
                if outcome == 'success':
                    results['completed_success'] += 1
                elif outcome == 'partial':
                    results['completed_partial'] += 1
                else:
                    results['completed_failure'] += 1

                completed_pilots.append({
                    'id': str(pilot.id),
                    'name': pilot.name[:50],
                    'outcome': outcome,
                    'hours': round(hours_running, 1),
                })

                # Update linked experiment
                try:
                    experiment = pilot.experiment
                    if experiment:
                        # Map pilot outcome to experiment status
                        exp_status_map = {
                            'success': 'success',
                            'partial': 'partial',
                            'failure': 'failure',
                            'inconclusive': 'inconclusive',
                        }
                        exp_status = exp_status_map.get(outcome, 'inconclusive')

                        # Simulate final KPI value based on outcome
                        kpi_progress = _simulate_kpi_progress(outcome, confidence)
                        experiment.current_value = f"{kpi_progress}%"

                        # Complete the experiment
                        experiment.complete(
                            status=exp_status,
                            result_summary=reasoning,
                            learnings=f"Pilot ran for {hours_running:.1f} hours. Outcome: {outcome}."
                        )

                        results['experiments_updated'] += 1

                        # Extract structured learning
                        learning = _extract_experiment_learning(experiment, outcome, decision)
                        if learning:
                            created_learnings.append(learning)
                            results['learnings_created'] += 1

                            # Update success patterns
                            pattern = DecisionTypeSuccessPattern.update_from_learning(learning)
                            if pattern:
                                results['patterns_updated'] += 1

                except Experiment.DoesNotExist:
                    logger.debug(f"🎯 [SESSION 618] No experiment for pilot {pilot.id}")

            except Exception as e:
                logger.error(f"🎯 [SESSION 618] Error evaluating pilot {pilot.id}: {e}")
                continue

        # Feed learnings to collective intelligence
        if created_learnings:
            _feed_learnings_to_collective_intelligence(created_learnings)

        # Send Discord notification
        if results['evaluated'] > 0:
            _send_pilot_evaluation_discord(results, completed_pilots[:5])

        logger.info(
            f"🎯 [SESSION 618] Pipeline complete: "
            f"{results['evaluated']} pilots evaluated, "
            f"{results['learnings_created']} learnings created"
        )

        return {
            'success': True,
            **results,
            'completed_pilots': completed_pilots[:10],  # Limit for response size
        }

    except Exception as e:
        logger.error(f"🎯 [SESSION 618] Pipeline failed: {e}", exc_info=True)
        return {'success': False, 'error': str(e)}




