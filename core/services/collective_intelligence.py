@dataclass
class AgentInsight:
    """Insight from a single agent"""
    agent_name: str
    topic: str
    insight_type: str  # observation, recommendation, warning, opportunity
    content: str
    confidence: float  # 0.0 - 1.0
    supporting_data: Dict[str, Any] = field(default_factory=dict)
    timestamp: datetime = field(default_factory=timezone.now)

    def to_dict(self) -> Dict[str, Any]:
        return {
            'agent_name': self.agent_name,
            'topic': self.topic,
            'insight_type': self.insight_type,
            'content': self.content,
            'confidence': self.confidence,
            'supporting_data': self.supporting_data,
            'timestamp': self.timestamp.isoformat()
        }


@dataclass
class CollectiveReport:
    """Report generated by multiple agents"""
    id: str
    topic: str
    summary: str
    participating_agents: List[str]
    insights: List[AgentInsight]
    recommendations: List[Dict[str, Any]]
    consensus_score: float  # How much agents agreed
    confidence_score: float  # Overall confidence
    knowledge_gaps: List[str]
    generated_at: datetime = field(default_factory=timezone.now)

    def to_dict(self) -> Dict[str, Any]:
        return {
            'id': self.id,
            'topic': self.topic,
            'summary': self.summary,
            'participating_agents': self.participating_agents,
            'insights': [i.to_dict() for i in self.insights],
            'recommendations': self.recommendations,
            'consensus_score': self.consensus_score,
            'confidence_score': self.confidence_score,
            'knowledge_gaps': self.knowledge_gaps,
            'generated_at': self.generated_at.isoformat()
        }


@dataclass
class KnowledgeGap:
    """Identified gap in agent knowledge"""
    domain: str
    description: str
    severity: str  # low, medium, high, critical
    affected_agents: List[str]
    suggested_sources: List[str]
    potential_impact: str
    discovered_at: datetime = field(default_factory=timezone.now)


@dataclass
class AgentImprovement:
    """Proposed improvement for an agent"""
    agent_name: str
    improvement_type: str  # capability, knowledge, performance, collaboration
    description: str
    expected_impact: str
    priority: int  # 1-5, 5 is highest
    evidence: Dict[str, Any] = field(default_factory=dict)
    estimated_effort: str = 'medium'  # low, medium, high


@dataclass
class CollaborationMonitor:
    """Real-time collaboration monitoring data"""
    active_collaborations: int
    pending_collaborations: int
    agents_collaborating: List[str]
    recent_completions: List[Dict[str, Any]]
    collaboration_health: str  # healthy, degraded, critical
    avg_response_time_ms: float
    success_rate_24h: float


