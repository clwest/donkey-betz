    def get_collective_stats(self) -> Dict[str, Any]:
        """Get comprehensive collective intelligence statistics"""
        try:
            from core.models_unified_system import (
                CollaborationSession,
                SharedKnowledge,
                AgentPerformanceMetric,
                InterAgentMessage,
                Agent,
                AgentKnowledgeSource,
                AgentSpiderConnection,
                AgentLearningConnection  # Session 243
            )

            # Collaboration stats
            total_collabs = CollaborationSession.objects.count()
            completed_collabs = CollaborationSession.objects.filter(status='completed').count()

            # Knowledge stats - use AgentKnowledgeSource if available, fallback to SharedKnowledge
            knowledge_source_count = AgentKnowledgeSource.objects.filter(is_active=True).count()
            total_knowledge = knowledge_source_count if knowledge_source_count > 0 else SharedKnowledge.objects.count()
            avg_effectiveness = SharedKnowledge.objects.aggregate(
                avg=Avg('effectiveness_score')
            )['avg'] or 0

            # Agent stats - use core.Agent model (the real 20 agents) with fallback
            real_agent_count = Agent.objects.filter(is_active=True).count()
            total_agents = real_agent_count if real_agent_count > 0 else AgentPerformanceMetric.objects.count()
            avg_quality = AgentPerformanceMetric.objects.aggregate(
                avg=Avg('quality_score')
            )['avg'] or 0

            # Spider connection stats (Session 242)
            spider_connections = AgentSpiderConnection.objects.count()

            # Learning connections (Session 243)
            learning_connections = AgentLearningConnection.objects.filter(is_active=True).count()

            # Message stats
            total_messages = InterAgentMessage.objects.count()

            # Top domains
            domain_stats = SharedKnowledge.objects.values('domain').annotate(
                count=Count('id')
            ).order_by('-count')[:5]

            # Top collaborating agents
            top_collaborators = AgentPerformanceMetric.objects.order_by(
                '-successful_collaborations'
            ).values('agent_name', 'successful_collaborations')[:5]

            return {
                'collaboration': {
                    'total': total_collabs,
                    'completed': completed_collabs,
                    'success_rate': completed_collabs / total_collabs if total_collabs > 0 else 0
                },
                'knowledge': {
                    'total_items': total_knowledge,
                    'avg_effectiveness': avg_effectiveness
                },
                'agents': {
                    'total': total_agents,
                    'avg_quality_score': avg_quality,
                    'spider_connections': spider_connections,  # Session 242
                    'learning_connections': learning_connections  # Session 243
                },
                'messages': {
                    'total': total_messages
                },
                'top_domains': list(domain_stats),
                'top_collaborators': list(top_collaborators),
                'generated_at': timezone.now().isoformat()
            }

        except Exception as e:
            self.logger.error(f"Error getting collective stats: {e}")
            return {'error': str(e)}


