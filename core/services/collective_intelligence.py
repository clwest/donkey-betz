    # =========================================================================
    # INSIGHT AGGREGATION
    # =========================================================================

    def aggregate_insights(self, topic: str, domains: List[str] = None) -> Dict[str, Any]:
        """
        Gather insights from all relevant agents on a topic.

        Args:
            topic: The topic to gather insights on
            domains: Optional list of domains to focus on

        Returns:
            Aggregated insights with consensus analysis
        """
        try:
            from core.models_unified_system import (
                SharedKnowledge,
                CollaborationSession,
                AgentPerformanceMetric
            )

            # Cache key for this query
            cache_key = f'collective_insights:{topic}:{",".join(domains or [])}'
            cached = cache.get(cache_key)
            if cached:
                return cached

            # Find relevant knowledge
            knowledge_query = SharedKnowledge.objects.all()

            if domains:
                knowledge_query = knowledge_query.filter(domain__in=domains)

            # Search for topic in titles and tags
            knowledge_query = knowledge_query.filter(
                Q(title__icontains=topic) |
                Q(tags__icontains=topic) |
                Q(description__icontains=topic)
            ).order_by('-effectiveness_score', '-created_at')[:50]

            insights = []
            agent_contributions = defaultdict(int)
            domain_coverage = defaultdict(list)

            for knowledge in knowledge_query:
                insight = AgentInsight(
                    agent_name=knowledge.source_agent,
                    topic=topic,
                    insight_type='knowledge',
                    content=knowledge.description,
                    confidence=min(knowledge.effectiveness_score / 100, 1.0),
                    supporting_data={
                        'knowledge_id': str(knowledge.id),
                        'domain': knowledge.domain,
                        'tags': knowledge.tags,
                        'learned_by_count': len(knowledge.learned_by_agents)
                    }
                )
                insights.append(insight)
                agent_contributions[knowledge.source_agent] += 1
                domain_coverage[knowledge.domain].append(knowledge.source_agent)

            # Get recent collaboration results related to topic
            recent_collabs = CollaborationSession.objects.filter(
                Q(task_description__icontains=topic) |
                Q(input_data__icontains=topic),
                status='completed'
            ).order_by('-completed_at')[:20]

            for collab in recent_collabs:
                if collab.output_data:
                    insight = AgentInsight(
                        agent_name=collab.requester_agent,
                        topic=topic,
                        insight_type='collaboration_result',
                        content=f"Collaboration on: {collab.task_description[:200]}",
                        confidence=collab.quality_score / 100 if collab.quality_score else 0.5,
                        supporting_data={
                            'collaboration_id': str(collab.id),
                            'collaboration_type': collab.collaboration_type,
                            'participating_agents': collab.participating_agents
                        }
                    )
                    insights.append(insight)
                    for agent in collab.participating_agents:
                        agent_contributions[agent] += 1

            # Calculate consensus and confidence
            confidence_scores = [i.confidence for i in insights]
            avg_confidence = sum(confidence_scores) / len(confidence_scores) if confidence_scores else 0.0

            # Determine consensus based on how many agents contributed similar insights
            unique_agents = len(agent_contributions)
            insights_per_agent = len(insights) / unique_agents if unique_agents > 0 else 0
            consensus_score = min(1.0, unique_agents / 5)  # Higher score with more agents

            result = {
                'topic': topic,
                'total_insights': len(insights),
                'unique_agents': unique_agents,
                'insights': [i.to_dict() for i in insights[:20]],  # Top 20
                'agent_contributions': dict(agent_contributions),
                'domain_coverage': {k: list(set(v)) for k, v in domain_coverage.items()},
                'consensus_score': consensus_score,
                'confidence_score': avg_confidence,
                'generated_at': timezone.now().isoformat()
            }

            # Cache for 5 minutes
            cache.set(cache_key, result, 300)

            return result

        except Exception as e:
            self.logger.error(f"Error aggregating insights for {topic}: {e}")
            return {
                'topic': topic,
                'total_insights': 0,
                'unique_agents': 0,
                'insights': [],
                'error': str(e)
            }

    # =========================================================================
    # COLLECTIVE REPORT GENERATION
    # =========================================================================

    def generate_collective_report(
        self,
        topic: str,
        report_type: str = 'comprehensive',
        include_agents: List[str] = None
    ) -> CollectiveReport:
        """
        Generate a report with input from multiple agents.

        Args:
            topic: The topic for the report
            report_type: Type of report (comprehensive, summary, action_items)
            include_agents: Optional list of specific agents to include

        Returns:
            CollectiveReport with multi-agent insights
        """
        import uuid

        try:
            from core.models_unified_system import (
                SharedKnowledge,
                AgentPerformanceMetric
            )

            # Gather all relevant insights
            aggregated = self.aggregate_insights(topic)

            insights = []
            for insight_data in aggregated.get('insights', []):
                insights.append(AgentInsight(
                    agent_name=insight_data['agent_name'],
                    topic=insight_data['topic'],
                    insight_type=insight_data['insight_type'],
                    content=insight_data['content'],
                    confidence=insight_data['confidence'],
                    supporting_data=insight_data.get('supporting_data', {})
                ))

            # Get top performing agents in relevant domains
            top_agents = AgentPerformanceMetric.objects.order_by(
                '-quality_score', '-total_executions'
            )[:10]

            participating_agents = list(set(
                aggregated.get('agent_contributions', {}).keys()
            ))

            if include_agents:
                participating_agents = [
                    a for a in participating_agents if a in include_agents
                ]

            # Generate recommendations based on insights
            recommendations = self._generate_recommendations(insights, topic)

            # Identify knowledge gaps
            knowledge_gaps = self._identify_topic_gaps(topic, insights)

            # Create summary
            summary = self._create_report_summary(
                topic, insights, recommendations, report_type
            )

            report = CollectiveReport(
                id=str(uuid.uuid4()),
                topic=topic,
                summary=summary,
                participating_agents=participating_agents,
                insights=insights,
                recommendations=recommendations,
                consensus_score=aggregated.get('consensus_score', 0.0),
                confidence_score=aggregated.get('confidence_score', 0.0),
                knowledge_gaps=knowledge_gaps
            )

            self.logger.info(
                f"Generated collective report on '{topic}' with "
                f"{len(participating_agents)} agents, {len(insights)} insights"
            )

            return report

        except Exception as e:
            self.logger.error(f"Error generating collective report: {e}")
            return CollectiveReport(
                id=str(uuid.uuid4()),
                topic=topic,
                summary=f"Error generating report: {str(e)}",
                participating_agents=[],
                insights=[],
                recommendations=[],
                consensus_score=0.0,
                confidence_score=0.0,
                knowledge_gaps=[]
            )

    def _generate_recommendations(
        self,
        insights: List[AgentInsight],
        topic: str
    ) -> List[Dict[str, Any]]:
        """Generate recommendations from insights"""
        recommendations = []

        # Group insights by confidence level
        high_confidence = [i for i in insights if i.confidence >= 0.7]
        medium_confidence = [i for i in insights if 0.4 <= i.confidence < 0.7]

        if high_confidence:
            recommendations.append({
                'type': 'action',
                'priority': 'high',
                'title': f'Act on high-confidence insights for {topic}',
                'description': f'{len(high_confidence)} insights have high confidence scores',
                'supporting_agents': list(set(i.agent_name for i in high_confidence))
            })

        if medium_confidence:
            recommendations.append({
                'type': 'investigation',
                'priority': 'medium',
                'title': f'Investigate medium-confidence findings on {topic}',
                'description': f'{len(medium_confidence)} insights need validation',
                'supporting_agents': list(set(i.agent_name for i in medium_confidence))
            })

        # Look for patterns in insight types
        insight_types = defaultdict(int)
        for insight in insights:
            insight_types[insight.insight_type] += 1

        if insight_types.get('warning', 0) > 2:
            recommendations.append({
                'type': 'warning',
                'priority': 'high',
                'title': f'Multiple warnings detected for {topic}',
                'description': f'{insight_types["warning"]} warning insights found',
                'supporting_agents': [
                    i.agent_name for i in insights if i.insight_type == 'warning'
                ]
            })

        return recommendations

    def _identify_topic_gaps(
        self,
        topic: str,
        insights: List[AgentInsight]
    ) -> List[str]:
        """Identify knowledge gaps for a topic"""
        gaps = []

        # Check if we have insights from key domains
        domains_covered = set()
        for insight in insights:
            if 'domain' in insight.supporting_data:
                domains_covered.add(insight.supporting_data['domain'])

        expected_domains = ['image', 'video', 'audio', 'research', 'workflow']
        missing_domains = set(expected_domains) - domains_covered

        for domain in missing_domains:
            gaps.append(f"No insights from {domain} domain for '{topic}'")

        # Check for low coverage
        if len(insights) < 5:
            gaps.append(f"Limited insight coverage for '{topic}' (only {len(insights)} insights)")

        # Check for low confidence overall
        avg_confidence = sum(i.confidence for i in insights) / len(insights) if insights else 0
        if avg_confidence < 0.5:
            gaps.append(f"Low overall confidence ({avg_confidence:.1%}) for '{topic}'")

        return gaps

    def _create_report_summary(
        self,
        topic: str,
        insights: List[AgentInsight],
        recommendations: List[Dict[str, Any]],
        report_type: str
    ) -> str:
        """Create a summary for the report"""
        if report_type == 'summary':
            return (
                f"Summary report on '{topic}': {len(insights)} insights gathered "
                f"with {len(recommendations)} recommendations."
            )
        elif report_type == 'action_items':
            action_count = len([r for r in recommendations if r['type'] == 'action'])
            return (
                f"Action items for '{topic}': {action_count} actions identified "
                f"from {len(insights)} agent insights."
            )
        else:  # comprehensive
            unique_agents = len(set(i.agent_name for i in insights))
            avg_confidence = sum(i.confidence for i in insights) / len(insights) if insights else 0
            return (
                f"Comprehensive analysis of '{topic}': {unique_agents} agents "
                f"contributed {len(insights)} insights with {avg_confidence:.1%} "
                f"average confidence. {len(recommendations)} recommendations generated."
            )

