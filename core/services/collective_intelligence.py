    def get_collaboration_network(self) -> Dict[str, Any]:
        """
        Get collaboration network data for visualization.

        Returns nodes (agents) and edges (collaborations) for
        network graph visualization.
        """
        try:
            from core.models_unified_system import (
                CollaborationSession,
                InterAgentMessage,
                AgentPerformanceMetric
            )

            # Build nodes from agent metrics
            nodes = []
            metrics = AgentPerformanceMetric.objects.all()

            for metric in metrics:
                nodes.append({
                    'id': metric.agent_name,
                    'label': metric.agent_name.replace('_', ' ').title(),
                    'size': min(50, 10 + metric.total_executions),  # Size based on activity
                    'color': self._get_agent_color(metric.quality_score),
                    'metrics': {
                        'executions': metric.total_executions,
                        'collaborations': metric.successful_collaborations,
                        'quality_score': metric.quality_score
                    }
                })

            # Build edges from collaboration history
            edges = []
            edge_weights = defaultdict(int)

            # From collaboration sessions
            sessions = CollaborationSession.objects.filter(
                status='completed'
            ).values('requester_agent', 'participating_agents')

            for session in sessions:
                requester = session['requester_agent']
                for participant in session['participating_agents'] or []:
                    if participant != requester:
                        key = tuple(sorted([requester, participant]))
                        edge_weights[key] += 1

            # From inter-agent messages
            messages = InterAgentMessage.objects.values(
                'sender_agent', 'receiver_agent'
            ).annotate(count=Count('id'))

            for msg in messages:
                key = tuple(sorted([msg['sender_agent'], msg['receiver_agent']]))
                edge_weights[key] += msg['count']

            # Create edge list
            for (agent1, agent2), weight in edge_weights.items():
                edges.append({
                    'source': agent1,
                    'target': agent2,
                    'weight': weight,
                    'width': min(10, 1 + weight // 5)  # Visual width
                })

            return {
                'nodes': nodes,
                'edges': edges,
                'stats': {
                    'total_nodes': len(nodes),
                    'total_edges': len(edges),
                    'total_collaborations': sum(edge_weights.values())
                },
                'generated_at': timezone.now().isoformat()
            }

        except Exception as e:
            self.logger.error(f"Error getting collaboration network: {e}")
            return {'nodes': [], 'edges': [], 'stats': {}, 'error': str(e)}

