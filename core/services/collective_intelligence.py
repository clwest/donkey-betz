    def get_collaboration_monitor(self) -> CollaborationMonitor:
        """
        Get real-time collaboration monitoring data.

        Returns current state of agent collaborations including
        active sessions, performance metrics, and health status.
        """
        try:
            from core.models_unified_system import CollaborationSession

            # Count active and pending
            active = CollaborationSession.objects.filter(
                status='active'
            ).count()

            pending = CollaborationSession.objects.filter(
                status='pending'
            ).count()

            # Get currently collaborating agents
            active_sessions = CollaborationSession.objects.filter(
                status__in=['active', 'pending']
            ).values_list('participating_agents', flat=True)

            collaborating_agents = set()
            for agents_list in active_sessions:
                if agents_list:
                    collaborating_agents.update(agents_list)

            # Recent completions (last hour)
            recent = CollaborationSession.objects.filter(
                status='completed',
                completed_at__gte=timezone.now() - timedelta(hours=1)
            ).order_by('-completed_at')[:10]

            recent_completions = [{
                'id': str(r.id),
                'requester': r.requester_agent,
                'type': r.collaboration_type,
                'quality_score': r.quality_score,
                'completed_at': r.completed_at.isoformat() if r.completed_at else None
            } for r in recent]

            # Calculate 24h success rate
            last_24h = CollaborationSession.objects.filter(
                created_at__gte=timezone.now() - timedelta(hours=24)
            )
            total_24h = last_24h.count()
            completed_24h = last_24h.filter(status='completed').count()
            success_rate = completed_24h / total_24h if total_24h > 0 else 1.0

            # Calculate average response time
            completed_recent = CollaborationSession.objects.filter(
                status='completed',
                completed_at__isnull=False
            ).order_by('-completed_at')[:50]

            response_times = []
            for session in completed_recent:
                if session.completed_at and session.created_at:
                    delta = (session.completed_at - session.created_at).total_seconds() * 1000
                    response_times.append(delta)

            avg_response = sum(response_times) / len(response_times) if response_times else 0

            # Determine health status
            if active + pending > 50 or success_rate < 0.5:
                health = 'critical'
            elif active + pending > 20 or success_rate < 0.7:
                health = 'degraded'
            else:
                health = 'healthy'

            return CollaborationMonitor(
                active_collaborations=active,
                pending_collaborations=pending,
                agents_collaborating=list(collaborating_agents),
                recent_completions=recent_completions,
                collaboration_health=health,
                avg_response_time_ms=avg_response,
                success_rate_24h=success_rate
            )

        except Exception as e:
            self.logger.error(f"Error getting collaboration monitor: {e}")
            return CollaborationMonitor(
                active_collaborations=0,
                pending_collaborations=0,
                agents_collaborating=[],
                recent_completions=[],
                collaboration_health='unknown',
                avg_response_time_ms=0,
                success_rate_24h=0
            )

