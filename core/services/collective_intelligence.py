    def orchestrate_multi_agent_task(
        self,
        task_description: str,
        required_capabilities: List[str] = None,
        max_agents: int = 5,
        timeout_seconds: int = 300
    ) -> Dict[str, Any]:
        """
        Orchestrate a complex task across multiple agents.

        Automatically selects best agents, coordinates their work,
        and aggregates results.
        """
        import uuid

        try:
            from agents.registry import get_agent_registry
            from core.models_unified_system import CollaborationSession

            orchestration_id = str(uuid.uuid4())
            start_time = timezone.now()

            # 1. Select agents for the task
            registry = get_agent_registry()
            all_agents = registry.list_agents()

            # Score agents based on task requirements
            scored_agents = []
            for agent in all_agents:
                score = 0

                # Capability matching
                if required_capabilities:
                    agent_caps = agent.get('capabilities', [])
                    matches = len(set(required_capabilities) & set(agent_caps))
                    score += matches * 10

                # Keyword matching
                keywords = agent.get('routing_keywords', [])
                task_lower = task_description.lower()
                for kw in keywords:
                    if kw.lower() in task_lower:
                        score += 5

                # Performance bonus
                metrics = agent.get('performance_metrics', {})
                score += metrics.get('success_rate', 0.5) * 10

                if score > 0:
                    scored_agents.append((agent, score))

            # Select top agents
            scored_agents.sort(key=lambda x: x[1], reverse=True)
            selected_agents = [a[0] for a in scored_agents[:max_agents]]

            if not selected_agents:
                return {
                    'orchestration_id': orchestration_id,
                    'status': 'failed',
                    'error': 'No suitable agents found for task',
                    'selected_agents': [],
                    'results': []
                }

            # 2. Create parallel collaboration sessions
            agent_names = [a['name'] for a in selected_agents]

            session = CollaborationSession.objects.create(
                requester_agent='collective_intelligence',
                collaboration_type='parallel',
                task_description=task_description,
                input_data={
                    'required_capabilities': required_capabilities or [],
                    'timeout_seconds': timeout_seconds
                },
                participating_agents=agent_names,
                status='active',
                user=self.user
            )

            # 3. Return orchestration info (actual execution would be async)
            return {
                'orchestration_id': orchestration_id,
                'session_id': str(session.id),
                'status': 'initiated',
                'selected_agents': agent_names,
                'agent_count': len(selected_agents),
                'task_description': task_description,
                'timeout_seconds': timeout_seconds,
                'started_at': start_time.isoformat()
            }

        except Exception as e:
            self.logger.error(f"Error orchestrating multi-agent task: {e}")
            return {
                'orchestration_id': str(uuid.uuid4()),
                'status': 'failed',
                'error': str(e),
                'selected_agents': [],
                'results': []
            }

    # =========================================================================
    # COLLABORATION NETWORK ANALYSIS
    # =========================================================================

    def get_collaboration_network(self) -> Dict[str, Any]:
        """
        Get collaboration network data for visualization.

        Returns nodes (agents) and edges (collaborations) for
        network graph visualization.
        """
        try:
            from core.models_unified_system import (
                CollaborationSession,
                InterAgentMessage,
                AgentPerformanceMetric
            )

            # Build nodes from agent metrics
            nodes = []
            metrics = AgentPerformanceMetric.objects.all()

            for metric in metrics:
                nodes.append({
                    'id': metric.agent_name,
                    'label': metric.agent_name.replace('_', ' ').title(),
                    'size': min(50, 10 + metric.total_executions),  # Size based on activity
                    'color': self._get_agent_color(metric.quality_score),
                    'metrics': {
                        'executions': metric.total_executions,
                        'collaborations': metric.successful_collaborations,
                        'quality_score': metric.quality_score
                    }
                })

            # Build edges from collaboration history
            edges = []
            edge_weights = defaultdict(int)

            # From collaboration sessions
            sessions = CollaborationSession.objects.filter(
                status='completed'
            ).values('requester_agent', 'participating_agents')

            for session in sessions:
                requester = session['requester_agent']
                for participant in session['participating_agents'] or []:
                    if participant != requester:
                        key = tuple(sorted([requester, participant]))
                        edge_weights[key] += 1

            # From inter-agent messages
            messages = InterAgentMessage.objects.values(
                'sender_agent', 'receiver_agent'
            ).annotate(count=Count('id'))

            for msg in messages:
                key = tuple(sorted([msg['sender_agent'], msg['receiver_agent']]))
                edge_weights[key] += msg['count']

            # Create edge list
            for (agent1, agent2), weight in edge_weights.items():
                edges.append({
                    'source': agent1,
                    'target': agent2,
                    'weight': weight,
                    'width': min(10, 1 + weight // 5)  # Visual width
                })

            return {
                'nodes': nodes,
                'edges': edges,
                'stats': {
                    'total_nodes': len(nodes),
                    'total_edges': len(edges),
                    'total_collaborations': sum(edge_weights.values())
                },
                'generated_at': timezone.now().isoformat()
            }

        except Exception as e:
            self.logger.error(f"Error getting collaboration network: {e}")
            return {'nodes': [], 'edges': [], 'stats': {}, 'error': str(e)}

    def _get_agent_color(self, quality_score: float) -> str:
        """Get color based on quality score"""
        if quality_score >= 80:
            return '#22c55e'  # Green
        elif quality_score >= 60:
            return '#eab308'  # Yellow
        elif quality_score >= 40:
            return '#f97316'  # Orange
        else:
            return '#ef4444'  # Red

