    def identify_knowledge_gaps(self) -> List[KnowledgeGap]:
        """
        Identify areas where agents lack knowledge.

        Analyzes collaboration failures, low-confidence responses,
        and missing domain coverage to identify gaps.
        """
        try:
            from core.models_unified_system import (
                SharedKnowledge,
                CollaborationSession,
                AgentPerformanceMetric
            )

            gaps = []

            # 1. Find domains with low knowledge density
            domain_counts = SharedKnowledge.objects.values('domain').annotate(
                count=Count('id'),
                avg_effectiveness=Avg('effectiveness_score')
            )

            expected_domains = {
                'image': 10, 'video': 5, 'audio': 5, 'research': 10,
                'workflow': 5, '3d': 3, 'character': 3
            }

            domain_data = {d['domain']: d for d in domain_counts}

            for domain, min_expected in expected_domains.items():
                domain_info = domain_data.get(domain, {'count': 0, 'avg_effectiveness': 0})
                if domain_info['count'] < min_expected:
                    gaps.append(KnowledgeGap(
                        domain=domain,
                        description=f"Insufficient knowledge in {domain} domain",
                        severity='medium' if domain_info['count'] > 0 else 'high',
                        affected_agents=self._get_agents_by_domain(domain),
                        suggested_sources=[
                            f"Training data for {domain}",
                            f"Expert consultations on {domain}",
                            f"Historical success patterns in {domain}"
                        ],
                        potential_impact=f"May affect quality of {domain}-related tasks"
                    ))

            # 2. Find collaboration failure patterns
            failed_collabs = CollaborationSession.objects.filter(
                status='failed',
                created_at__gte=timezone.now() - timedelta(days=7)
            ).values('collaboration_type').annotate(count=Count('id'))

            for collab_data in failed_collabs:
                if collab_data['count'] >= 3:
                    gaps.append(KnowledgeGap(
                        domain='collaboration',
                        description=f"High failure rate in {collab_data['collaboration_type']} collaborations",
                        severity='high' if collab_data['count'] >= 5 else 'medium',
                        affected_agents=['all'],
                        suggested_sources=[
                            "Review failed collaboration logs",
                            "Improve error handling",
                            "Add retry mechanisms"
                        ],
                        potential_impact=f"{collab_data['count']} failures in past 7 days"
                    ))

            # 3. Find agents with low performance scores
            low_performers = AgentPerformanceMetric.objects.filter(
                total_executions__gte=5,
                quality_score__lt=50
            )

            for agent in low_performers:
                gaps.append(KnowledgeGap(
                    domain='performance',
                    description=f"Agent {agent.agent_name} has low quality score",
                    severity='medium',
                    affected_agents=[agent.agent_name],
                    suggested_sources=[
                        "Review agent configuration",
                        "Analyze failure patterns",
                        "Consider retraining or reconfiguration"
                    ],
                    potential_impact=f"Quality score: {agent.quality_score}%"
                ))

            self.logger.info(f"Identified {len(gaps)} knowledge gaps")
            return gaps

        except Exception as e:
            self.logger.error(f"Error identifying knowledge gaps: {e}")
            return []

    def _get_agents_by_domain(self, domain: str) -> List[str]:
        """Get agents that work in a specific domain"""
        try:
            from agents.registry import get_agent_registry
            registry = get_agent_registry()
            agents = registry.list_agents(specialization=domain)
            return [a['name'] for a in agents]
        except Exception:
            return []

