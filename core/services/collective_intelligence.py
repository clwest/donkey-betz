    def propose_agent_improvements(self) -> List[AgentImprovement]:
        """
        Propose improvements for agents based on learning data.

        Analyzes performance metrics, collaboration patterns, and
        knowledge gaps to suggest actionable improvements.
        """
        try:
            from core.models_unified_system import (
                AgentPerformanceMetric,
                CollaborationSession,
                SharedKnowledge
            )

            improvements = []

            # 1. Analyze performance metrics
            all_metrics = AgentPerformanceMetric.objects.all()

            for metric in all_metrics:
                # Low success rate
                if metric.total_executions >= 10 and metric.successful_executions / max(metric.total_executions, 1) < 0.7:
                    improvements.append(AgentImprovement(
                        agent_name=metric.agent_name,
                        improvement_type='performance',
                        description=f"Success rate below 70% ({metric.successful_executions}/{metric.total_executions})",
                        expected_impact='Improve task completion reliability',
                        priority=4,
                        evidence={
                            'total_executions': metric.total_executions,
                            'successful': metric.successful_executions,
                            'success_rate': metric.successful_executions / max(metric.total_executions, 1)
                        }
                    ))

                # Low collaboration
                if metric.total_executions >= 20 and metric.successful_collaborations < 2:
                    improvements.append(AgentImprovement(
                        agent_name=metric.agent_name,
                        improvement_type='collaboration',
                        description='Rarely collaborates with other agents',
                        expected_impact='Increase problem-solving capability through collaboration',
                        priority=3,
                        evidence={
                            'executions': metric.total_executions,
                            'collaborations': metric.successful_collaborations
                        }
                    ))

                # Low knowledge sharing
                if metric.knowledge_contributions == 0 and metric.total_executions >= 10:
                    improvements.append(AgentImprovement(
                        agent_name=metric.agent_name,
                        improvement_type='knowledge',
                        description='Not contributing to shared knowledge base',
                        expected_impact='Enable other agents to learn from this agent\'s expertise',
                        priority=2,
                        evidence={
                            'executions': metric.total_executions,
                            'contributions': metric.knowledge_contributions
                        }
                    ))

            # 2. Find capability gaps based on consultation patterns
            consultations = CollaborationSession.objects.filter(
                collaboration_type='consultation',
                status='completed'
            ).values('requester_agent').annotate(count=Count('id'))

            frequent_requesters = [c for c in consultations if c['count'] >= 5]
            for requester in frequent_requesters:
                improvements.append(AgentImprovement(
                    agent_name=requester['requester_agent'],
                    improvement_type='capability',
                    description=f"Frequently requests consultations ({requester['count']} times)",
                    expected_impact='Could benefit from expanded internal capabilities',
                    priority=2,
                    evidence={'consultation_count': requester['count']},
                    estimated_effort='high'
                ))

            # 3. Identify agents that could benefit from learning
            knowledge_items = SharedKnowledge.objects.filter(
                effectiveness_score__gte=70
            ).values('domain').annotate(count=Count('id'))

            high_value_domains = [k['domain'] for k in knowledge_items if k['count'] >= 3]

            for metric in all_metrics:
                # Check if agent should learn from high-value domains
                specs = metric.specialization_scores or {}
                for domain in high_value_domains:
                    if domain not in specs or specs[domain] < 50:
                        improvements.append(AgentImprovement(
                            agent_name=metric.agent_name,
                            improvement_type='knowledge',
                            description=f"Could benefit from {domain} domain knowledge",
                            expected_impact=f'Expand capabilities in {domain} area',
                            priority=2,
                            evidence={
                                'current_score': specs.get(domain, 0),
                                'available_knowledge': True
                            },
                            estimated_effort='low'
                        ))

            # Sort by priority
            improvements.sort(key=lambda x: x.priority, reverse=True)

            self.logger.info(f"Proposed {len(improvements)} agent improvements")
            return improvements[:20]  # Top 20 improvements

        except Exception as e:
            self.logger.error(f"Error proposing improvements: {e}")
            return []

