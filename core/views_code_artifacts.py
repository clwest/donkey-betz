"""
CodeArtifact API - Review and manage autonomous code outputs.

Session 1012: Patch-first workflow so code generated by agents on Railway
(where no writable workspace exists) is captured for human review.
"""

import logging

from django.utils import timezone
from rest_framework import serializers, status, viewsets
from rest_framework.decorators import action
from rest_framework.permissions import IsAuthenticated
from rest_framework.response import Response

from core.models_code_artifacts import CodeArtifact

logger = logging.getLogger(__name__)


class CodeArtifactSerializer(serializers.ModelSerializer):
    class Meta:
        model = CodeArtifact
        fields = [
            'id', 'created_at',
            'agent_name', 'agent_execution', 'initiative', 'trace_id',
            'kind', 'status', 'target_path',
            'content', 'content_before', 'description',
            'review_note', 'reviewed_by', 'reviewed_at',
        ]
        read_only_fields = [
            'id', 'created_at',
            'agent_name', 'agent_execution', 'initiative', 'trace_id',
            'kind', 'target_path', 'content', 'content_before', 'description',
            'reviewed_by', 'reviewed_at',
        ]


class CodeArtifactListSerializer(serializers.ModelSerializer):
    """Lightweight serializer for list view (omits large content fields)."""

    class Meta:
        model = CodeArtifact
        fields = [
            'id', 'created_at',
            'agent_name', 'trace_id',
            'kind', 'status', 'target_path', 'description',
            'reviewed_at',
        ]


class CodeArtifactViewSet(viewsets.ModelViewSet):
    """CRUD + approve/reject for CodeArtifact records."""

    permission_classes = [IsAuthenticated]
    http_method_names = ['get', 'post', 'head', 'options']

    def get_serializer_class(self):
        if self.action == 'list':
            return CodeArtifactListSerializer
        return CodeArtifactSerializer

    def get_queryset(self):
        qs = CodeArtifact.objects.all()

        # Filterable query params
        artifact_status = self.request.query_params.get('status')
        if artifact_status:
            qs = qs.filter(status=artifact_status)

        agent_name = self.request.query_params.get('agent_name')
        if agent_name:
            qs = qs.filter(agent_name__icontains=agent_name)

        initiative_id = self.request.query_params.get('initiative')
        if initiative_id:
            qs = qs.filter(initiative_id=initiative_id)

        kind = self.request.query_params.get('kind')
        if kind:
            qs = qs.filter(kind=kind)

        return qs

    @action(detail=True, methods=['post'])
    def approve(self, request, pk=None):
        """Mark an artifact as approved."""
        artifact = self.get_object()
        if artifact.status not in ('pending', 'rejected'):
            return Response(
                {'error': f'Cannot approve artifact with status "{artifact.status}"'},
                status=status.HTTP_400_BAD_REQUEST,
            )
        artifact.status = 'approved'
        artifact.reviewed_by = request.user
        artifact.reviewed_at = timezone.now()
        artifact.review_note = request.data.get('review_note', '')
        artifact.save(update_fields=['status', 'reviewed_by', 'reviewed_at', 'review_note'])
        return Response(CodeArtifactSerializer(artifact).data)

    @action(detail=True, methods=['post'])
    def reject(self, request, pk=None):
        """Mark an artifact as rejected."""
        artifact = self.get_object()
        if artifact.status not in ('pending', 'approved'):
            return Response(
                {'error': f'Cannot reject artifact with status "{artifact.status}"'},
                status=status.HTTP_400_BAD_REQUEST,
            )
        artifact.status = 'rejected'
        artifact.reviewed_by = request.user
        artifact.reviewed_at = timezone.now()
        artifact.review_note = request.data.get('review_note', '')
        artifact.save(update_fields=['status', 'reviewed_by', 'reviewed_at', 'review_note'])
        return Response(CodeArtifactSerializer(artifact).data)
