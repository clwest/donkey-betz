        recent_dup = AgentExecution.objects.filter(
            agent__name=agent_name,
            created_at__gte=now - timedelta(hours=6),
            input_data__task__startswith=title_prefix,
        ).exists()
        if recent_dup:
            skipped.append({'id': str(item.id), 'agent': agent_name, 'reason': 'dedup'})
            continue

