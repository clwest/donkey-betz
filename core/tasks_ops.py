                            alert.discord_sent = True
                            alert.discord_sent_at = timezone.now()
                            alert.save(update_fields=['discord_sent', 'discord_sent_at'])
                            event.discord_sent = True
                            event.discord_sent_at = timezone.now()
                            discord_sent += 1

