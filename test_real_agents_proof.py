    print("\n🧠 CHECKING LEGENDARY ADVISORS...")
    with connection.cursor() as cursor:
        cursor.execute("SELECT COUNT(*) FROM legendary_advisors WHERE is_active = true")
        advisor_count = cursor.fetchone()[0]

