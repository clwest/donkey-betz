import React, { useState, useEffect } from 'react';
import { LineChart, Line, XAxis, YAxis, Tooltip, CartesianGrid } from 'recharts';
import { ToastContainer, toast } from 'react-toastify';
import 'react-toastify/dist/ReactToastify.css';

const AGENT_WS_URL = 'ws://localhost:8000/ws/agent-monitor/';

const Dashboard = () => {
  const [agentData, setAgentData] = useState([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState(null);
  const [performanceAlerts, setPerformanceAlerts] = useState([]);

  useEffect(() => {
    const socket = new WebSocket(AGENT_WS_URL);

    socket.onopen = () => {
      console.log('WebSocket connected');
      setLoading(false);
    };

    socket.onmessage = (event) => {
      const data = JSON.parse(event.data);
      setAgentData(prevData => [...prevData, data]);

      if (data.successRate < 50) {
        setPerformanceAlerts(prevAlerts => [...prevAlerts, `Alert: Agent ${data.agentId} has a low success rate!`]);
        toast.error(`Agent ${data.agentId} has a low success rate!`);
      }
    };

    socket.onerror = (event) => {
      setError('WebSocket error: ' + event.message);
      setLoading(false);
    };

    socket.onclose = () => {
      console.log('WebSocket connection closed');
    };

    return () => {
      socket.close();
    };
  }, []);

  const successRateData = agentData.map(agent => ({
    name: agent.agentId,
    success: agent.successRate,
    failure: 100 - agent.successRate,
  }));

  return (
    <div className="bg-gray-900 text-white p-6 min-h-screen">
      <h1 className="text-3xl font-bold mb-6">Real-Time Agent Performance Dashboard</h1>
      {loading ? (
        <div className="flex justify-center items-center h-full">
          <span className="loader"></span>
        </div>
      ) : error ? (
        <div className="text-red-500">{error}</div>
      ) : (
        <div className="grid grid-cols-1 md:grid-cols-2 gap-6">
          <div className="bg-gray-800 p-4 rounded-lg shadow-lg">
            <h2 className="text-xl font-semibold mb-4">Agent Success Rates</h2>
            <LineChart width={500} height={300} data={successRateData}>
              <XAxis dataKey="name" />
              <YAxis />
              <Tooltip />
              <CartesianGrid strokeDasharray="3 3" />
              <Line type="monotone" dataKey="success" stroke="#4caf50" />
              <Line type="monotone" dataKey="failure" stroke="#f44336" />
            </LineChart>
          </div>
          <div className="bg-gray-800 p-4 rounded-lg shadow-lg">
            <h2 className="text-xl font-semibold mb-4">Performance Alerts</h2>
            <ul>
              {performanceAlerts.map((alert, index) => (
                <li key={index} className="text-red-400">{alert}</li>
              ))}
            </ul>
          </div>
        </div>
      )}
      <ToastContainer />
    </div>
  );
};

export default Dashboard;


