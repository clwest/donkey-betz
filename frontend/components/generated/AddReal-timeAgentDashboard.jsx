import React, { useEffect, useState } from 'react';
import { Line } from 'react-chartjs-2';
import { ToastContainer, toast } from 'react-toastify';
import 'react-toastify/dist/ReactToastify.css';

const AgentPerformanceDashboard = () => {
    const [agentData, setAgentData] = useState([]);
    const [loading, setLoading] = useState(true);
    const [error, setError] = useState(null);
    const [chartData, setChartData] = useState({ labels: [], datasets: [] });

    useEffect(() => {
        const ws = new WebSocket('ws://localhost:8000/ws/agent-monitor/');

        ws.onopen = () => {
            console.log('WebSocket connected');
        };

        ws.onmessage = (event) => {
            const data = JSON.parse(event.data);
            setLoading(false);
            if (data.error) {
                setError(data.error);
                toast.error(data.error);
                return;
            }

            setAgentData((prevData) => {
                const newData = [...prevData, data];
                return newData.slice(-10); // Keep the last 10 entries
            });

            updateChart(data);
        };

        ws.onerror = (error) => {
            setLoading(false);
            setError('WebSocket error: ' + error.message);
            toast.error('WebSocket error: ' + error.message);
        };

        ws.onclose = () => {
            console.log('WebSocket disconnected');
        };

        return () => {
            ws.close();
        };
    }, []);

    const updateChart = (data) => {
        setChartData({
            labels: agentData.map((_, index) => index + 1),
            datasets: [
                {
                    label: 'Success Rate',
                    data: agentData.map(d => d.successRate),
                    borderColor: 'rgba(75, 192, 192, 1)',
                    backgroundColor: 'rgba(75, 192, 192, 0.2)',
                    fill: true,
                },
                {
                    label: 'Failure Rate',
                    data: agentData.map(d => d.failureRate),
                    borderColor: 'rgba(255, 99, 132, 1)',
                    backgroundColor: 'rgba(255, 99, 132, 0.2)',
                    fill: true,
                }
            ]
        });
    };

    return (
        <div className="bg-gray-900 text-white p-6 rounded-lg shadow-lg">
            <h1 className="text-2xl font-bold mb-4">Agent Performance Dashboard</h1>
            {loading && <p>Loading...</p>}
            {error && <p className="text-red-500">{error}</p>}
            <div className="my-4">
                <Line data={chartData} />
            </div>
            <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
                {agentData.map((agent, index) => (
                    <div key={index} className="bg-gray-800 p-4 rounded-lg shadow">
                        <h2 className="text-xl">{agent.name}</h2>
                        <p>Success Rate: {agent.successRate}%</p>
                        <p>Failure Rate: {agent.failureRate}%</p>
                    </div>
                ))}
            </div>
            <ToastContainer />
        </div>
    );
};

export default AgentPerformanceDashboard;


